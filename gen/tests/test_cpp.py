"""The C++ message headers: the field mapping, the frozen text and the bundle's bytes.

Covers the generator side of the runtime API: every field kind the nine
bundled types use, the frozen header of each type, the layout checks that tie
the C++ struct to the C struct the bundle's descriptors describe, and the file
set the bundle ships.
"""

import subprocess
from pathlib import Path

import pytest
from r2s_gen import bounds, bundle, cpp, descriptors, msgs, typehash
from r2s_gen.version import __version__
from support import write_message

ROOT = Path(__file__).resolve().parents[2]
CPP_INCLUDE = ROOT / "cpp" / "include"
CORE_INCLUDE = ROOT / "core" / "include"

# The field kinds the nine bundled types use, each with the C++ member it maps
# to. The mapping mirrors the C emission, so the two layouts agree.
FIELD_KINDS = [
    ("bool value", "    uint8_t value;"),
    ("byte value", "    uint8_t value;"),
    ("char value", "    uint8_t value;"),
    ("int8 value", "    int8_t value;"),
    ("uint8 value", "    uint8_t value;"),
    ("int16 value", "    int16_t value;"),
    ("uint16 value", "    uint16_t value;"),
    ("int32 value", "    int32_t value;"),
    ("uint32 value", "    uint32_t value;"),
    ("int64 value", "    int64_t value;"),
    ("uint64 value", "    uint64_t value;"),
    ("float32 value", "    float value;"),
    ("float64 value", "    double value;"),
    ("string value", "    char value[17];"),
    ("float64[4] values", "    double values[4];"),
    ("string[3] values", "    char values[3][17];"),
]


def emit_for(tmp_path, definitions, type_name, bound_map=None, default_string_bound=16):
    """The C++ header of one type, from a throwaway message package."""
    root = tmp_path / "messages"
    for name, text in definitions.items():
        write_message(root, name, text)
    repository = msgs.MessageRepository(msg_paths=[root])
    resolved = bounds.resolve(
        repository,
        [type_name],
        bounds=bound_map or {},
        default_string_bound=default_string_bound,
    )
    return cpp.emit_message_hpp(resolved, type_name, repository=repository)


def bundled_resolved(distro="jazzy"):
    """The resolved bundled types and the repository they came from."""
    repository = msgs.MessageRepository(distro=distro)
    resolved = bounds.resolve(
        repository,
        list(bundle.BUNDLED_TYPES),
        bounds=dict(bundle.BUNDLE_BOUNDS),
        default_string_bound=bundle.DEFAULT_STRING_BOUND,
    )
    return resolved, repository


def emit_bundled(resolved, repository, type_name, distro="jazzy"):
    """The C++ header of a bundled type, with the banner the bundle gives it."""
    return cpp.emit_message_hpp(
        resolved, type_name, repository=repository, distro=distro, digest=bundle._digest(distro)
    )


def frozen(type_name):
    """The frozen header of a type, as the tree holds it."""
    return (CPP_INCLUDE / cpp.message_path(type_name)).read_text(encoding="utf-8")


@pytest.mark.parametrize(("definition", "expected"), FIELD_KINDS)
def test_a_scalar_field_maps_to_its_cpp_type(tmp_path, definition, expected):
    header = emit_for(tmp_path, {"pkg/msg/One": f"{definition}\n"}, "pkg/msg/One")

    assert expected in header


def test_a_nested_message_field_maps_to_the_nested_cpp_type(tmp_path):
    header = emit_for(
        tmp_path,
        {"pkg/msg/One": "pkg/msg/Two inner\n", "pkg/msg/Two": "int32 value\n"},
        "pkg/msg/One",
    )

    assert "    pkg::msg::Two inner;" in header
    assert '#include "pkg/msg/two.hpp"' in header


def test_a_bounded_sequence_maps_to_a_struct_with_its_count(tmp_path):
    header = emit_for(
        tmp_path,
        {"pkg/msg/One": "int32[] values\n"},
        "pkg/msg/One",
        bound_map={"pkg/msg/One.values": 4},
    )

    assert "    struct values_sequence {" in header
    assert "        int32_t data[4];" in header
    assert "        uint8_t size;" in header
    assert "    };" in header
    assert "    values_sequence values;" in header


def test_a_bounded_sequence_of_strings_maps_to_a_char_array_per_element(tmp_path):
    header = emit_for(
        tmp_path,
        {"pkg/msg/One": "string[] names\n"},
        "pkg/msg/One",
        bound_map={"pkg/msg/One.names": 4},
    )

    assert "        char data[4][17];" in header
    assert "    names_sequence names;" in header


def test_a_sequence_above_255_elements_holds_a_two_byte_count(tmp_path):
    header = emit_for(
        tmp_path,
        {"pkg/msg/One": "int32[] values\n"},
        "pkg/msg/One",
        bound_map={"pkg/msg/One.values": 300},
    )

    assert "        uint16_t size;" in header


def test_the_header_names_the_generator_and_the_type(tmp_path):
    header = emit_for(tmp_path, {"pkg/msg/One": "int32 value\n"}, "pkg/msg/One")

    assert f"Generated by r2s-gen {__version__}" in header
    assert "namespace pkg" in header
    assert "namespace msg" in header
    assert "struct One" in header


def test_the_header_declares_the_trait_of_its_type(tmp_path):
    header = emit_for(tmp_path, {"pkg/msg/One": "int32 value\n"}, "pkg/msg/One")

    assert "namespace r2s" in header
    assert "template <typename T> struct msg_traits;" in header
    assert "struct msg_traits<pkg::msg::One>" in header
    assert "static const r2s_codec_table_t *table()" in header
    assert "static uint16_t type_index()" in header
    assert "static const char *type_name()" in header
    assert "static const uint8_t *type_hash()" in header


def test_the_trait_is_a_specialization_of_the_primary_template(tmp_path):
    header = emit_for(tmp_path, {"pkg/msg/One": "int32 value\n"}, "pkg/msg/One")

    assert "template <> struct msg_traits<pkg::msg::One> {" in header


@pytest.mark.parametrize("type_name", bundle.BUNDLED_TYPES)
def test_the_frozen_header_is_emitted(type_name):
    resolved, repository = bundled_resolved()

    header = emit_bundled(resolved, repository, type_name)

    assert header == frozen(type_name)


@pytest.mark.parametrize("type_name", bundle.BUNDLED_TYPES)
def test_the_frozen_header_compiles_on_the_host(tmp_path, type_name):
    source = tmp_path / "check.cpp"
    source.write_text(f'#include "{cpp.message_path(type_name)}"\n', encoding="utf-8")

    compiled = subprocess.run(
        [
            "g++",
            "-std=c++11",
            "-Wall",
            "-Wextra",
            "-Werror",
            "-pedantic",
            "-Wconversion",
            "-fsyntax-only",
            "-I",
            str(CORE_INCLUDE),
            "-I",
            str(CPP_INCLUDE),
            str(source),
        ],
        capture_output=True,
        text=True,
    )

    assert compiled.returncode == 0, compiled.stderr


@pytest.mark.parametrize("type_name", bundle.BUNDLED_TYPES)
def test_the_frozen_header_ties_its_struct_to_the_c_struct(type_name):
    header = frozen(type_name)
    c_name = cpp.cpp_type(type_name).replace("::", "__").replace("pkg___", "__msg__")

    assert f"R2S_CPP_SAME_SIZE({cpp.cpp_type(type_name)}, {c_name});" in header
    assert "R2S_CPP_SAME_OFFSET" in header


@pytest.mark.parametrize("type_name", bundle.BUNDLED_TYPES)
def test_the_header_names_the_bundle_table_of_its_closure(type_name):
    resolved, repository = bundled_resolved()
    header = emit_bundled(resolved, repository, type_name)
    suffix = cpp.suffix(type_name)
    bundled = bundle.bundle("jazzy")

    assert f"extern const r2s_codec_table_t r2s_bundled_table_{suffix};" in header
    assert f"const r2s_codec_table_t r2s_bundled_table_{suffix}" in bundled["src/r2s_bundled.c"]


@pytest.mark.parametrize("type_name", bundle.BUNDLED_TYPES)
def test_the_header_reads_the_bundle_bytes_of_its_closure(type_name):
    """The header's table is the bundle's, so the bytes are the bundle's bytes."""
    resolved, repository = bundled_resolved()
    table = descriptors.build(resolved, [type_name])
    bundled = bundle.bundle("jazzy")["src/r2s_bundled.c"]
    suffix = cpp.suffix(type_name)

    for line in descriptors.record_lines(table):
        assert line in bundled, line
    for line in descriptors.entry_lines(table):
        assert line in bundled, line
    assert f"const uint8_t R2S_FLASH r2s_bundled_records_{suffix}[] = {{" in bundled
    assert f"const uint8_t R2S_FLASH r2s_bundled_entries_{suffix}[] = {{" in bundled


@pytest.mark.parametrize("type_name", bundle.BUNDLED_TYPES)
def test_the_type_index_is_the_records_own_index(type_name):
    resolved, repository = bundled_resolved()
    table = descriptors.build(resolved, [type_name])
    header = emit_bundled(resolved, repository, type_name)

    assert f"return {table.index_of[type_name]}u;" in header


@pytest.mark.parametrize("type_name", bundle.BUNDLED_TYPES)
def test_the_type_index_is_the_index_the_bundle_announces(type_name):
    resolved, repository = bundled_resolved()
    header = emit_bundled(resolved, repository, type_name)
    bundled = bundle.bundle("jazzy")["src/r2s_bundled.h"]
    suffix = cpp.suffix(type_name)
    announced = bundled.split(f"#define R2S_BUNDLED_INDEX_{suffix} ")[1].split("\n")[0]

    assert f"return {announced};" in header


@pytest.mark.parametrize("type_name", bundle.BUNDLED_TYPES)
def test_the_header_carries_the_hash_the_topic_table_announces(type_name):
    resolved, repository = bundled_resolved()
    header = emit_bundled(resolved, repository, type_name)
    digest = typehash.type_hash(repository, type_name)
    announced = bytes.fromhex(digest[len("RIHS01_") :])[:8]

    assert "static const uint8_t hash[] = {" in header
    for byte in announced:
        assert f"0x{byte:02x}u" in header


def test_the_bundle_ships_every_frozen_message_header():
    files = bundle.bundle("jazzy")

    for type_name in bundle.BUNDLED_TYPES:
        path = f"src/{cpp.message_path(type_name)}"
        assert path in files
        assert files[path] == frozen(type_name)


def test_the_bundle_ships_the_frozen_c_header_the_message_headers_need():
    files = bundle.bundle("jazzy")

    assert files["src/r2s_bundled.h"] == (CPP_INCLUDE / cpp.BUNDLED_HEADER).read_text(encoding="utf-8")


