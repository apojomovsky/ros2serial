def test_the_umbrella_header_serves_the_runtime_api():
    header = (CPP_INCLUDE / "ros2serial.h").read_text(encoding="utf-8")

    assert "#if defined(__cplusplus) && !defined(R2S_TOPICS)" in header
    assert '#include "r2s/runtime.hpp"' in header


def test_the_message_header_path_follows_the_rclcpp_convention():
    assert cpp.message_path("std_msgs/msg/Float32") == "std_msgs/msg/float32.hpp"
    assert cpp.message_path("sensor_msgs/msg/JointState") == "sensor_msgs/msg/joint_state.hpp"
    assert cpp.message_path("builtin_interfaces/msg/Time") == "builtin_interfaces/msg/time.hpp"


def test_the_cpp_type_follows_the_ros_2_naming():
    assert cpp.cpp_type("std_msgs/msg/Float32") == "std_msgs::msg::Float32"
    assert cpp.cpp_type("sensor_msgs/msg/JointState") == "sensor_msgs::msg::JointState"
