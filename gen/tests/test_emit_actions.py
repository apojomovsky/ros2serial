"""Action emission: the action table, IDs, hashes and descriptor indices.

Covers actions past the descriptors: IDs from 0 in configuration order,
goal, feedback and result descriptor indices from the shared depth-first
walk, RIHS01 action hashes, and the empty section when the config has none.
The golden pair pins the exact bytes; the C compile test proves they are C99.
"""

import shutil
import subprocess
from pathlib import Path

import pytest
from r2s_gen import actions
from r2s_gen import bounds
from r2s_gen import config
from r2s_gen import msgs
from r2s_gen.config import Config
from r2s_gen.version import __version__

GOLDEN = Path(__file__).parent / 'golden' / 'actions_emit'
ROOT = Path(__file__).resolve().parents[2]
CORE_INCLUDE = ROOT / 'core' / 'include'

CONFIG_TEXT = """\
node: base_controller
topics:
  - name: battery
    type: std_msgs/msg/Float32
    direction: pub
actions:
  - name: spin
    type: tf2_msgs/action/LookupTransform
bounds:
  std_msgs/msg/String.data: 8
  tf2_msgs/action/LookupTransform_Goal.target_frame: 16
  tf2_msgs/action/LookupTransform_Goal.source_frame: 16
  tf2_msgs/action/LookupTransform_Goal.fixed_frame: 16
  tf2_msgs/msg/TF2Error.error_string: 16
  std_msgs/msg/Header.frame_id: 16
  geometry_msgs/msg/TransformStamped.child_frame_id: 16
"""

ACTION_HASH = bytes.fromhex('0b8adf6bc0b59588')


def write_config(root: Path, text: str = CONFIG_TEXT):
    path = root / 'r2s.yaml'
    path.write_text(text, encoding='utf-8')
    return path


def load_actions(root: Path):
    loaded = config.load(write_config(root))
    repository = msgs.MessageRepository(distro='jazzy')
    resolved = bounds.resolve(
        repository,
        [topic.type_name for topic in loaded.topics] + actions.roots(loaded),
        bounds=dict(loaded.bounds),
    )
    return loaded, resolved, repository


def build_loaded(loaded, resolved, repository, source='r2s.yaml'):
    return actions.build(loaded, resolved, repository, source=source)


def test_goal_feedback_and_result_share_one_descriptor_walk(tmp_path):
    loaded, resolved, repository = load_actions(tmp_path)
    table = build_loaded(loaded, resolved, repository)

    assert [(entry.name, entry.type_name) for entry in table.entries] == [
        ('spin', 'tf2_msgs/action/LookupTransform')
    ]
    assert [entry.action_id for entry in table.entries] == [0]
    goal, feedback, result = (
        table.entries[0].type_index_goal,
        table.entries[0].type_index_feedback,
        table.entries[0].type_index_result,
    )
    assert len({goal, feedback, result}) == 3
    assert table.entries[0].type_hash == ACTION_HASH


def test_an_empty_action_section_emits_nothing(tmp_path):
    loaded = Config(node='base_controller', topics=(), actions=(), distro='jazzy')
    table = actions.build(loaded, {}, msgs.MessageRepository(msg_paths=[tmp_path]))

    assert table.entries == ()
    assert actions.roots(loaded) == []
    assert actions.emit_h(table) == (
        f'/* Generated by r2s-gen {__version__} from the configured actions; do not edit. */\n'
        '/* Actions in configuration order: IDs run from 0, each action\n'
        ' * names its goal, feedback and result by the descriptor indices the\n'
        ' * depth-first walk fixed (DSC-11). The MCU serves every action it\n'
        ' * declares (ACT-7). */\n'
        '\n'
        '#define R2S_ACTION_COUNT 0u'
    )
    assert actions.emit_c(table) == (
        f'/* Generated by r2s-gen {__version__} from the configured actions; do not edit. */\n'
        '/* The announced actions (ACT-1, ACT-7): the hashes are the first 8 bytes\n'
        " * of each action's RIHS01 hash, and the goal, feedback and result types are\n"
        ' * descriptor indices into the shared table. */\n'
        'const r2s_action_t R2S_FLASH r2s_actions[R2S_ACTION_COUNT] = {\n'
        '};\n'
    )


def test_more_actions_than_the_core_tracks_is_an_error(tmp_path):
    many = tuple(
        config.Action(name=f'spin{i}', type_name='tf2_msgs/action/LookupTransform')
        for i in range(actions.MAX_ACTIONS + 1)
    )
    loaded = Config(node='base_controller', topics=(), actions=many, distro='jazzy')
    repository = msgs.MessageRepository(msg_paths=[tmp_path])

    with pytest.raises(msgs.MessageError) as caught:
        actions.build(loaded, {}, repository)

    over = actions.MAX_ACTIONS + 1
    assert str(caught.value) == (
        f'r2s.yaml: actions: {over} actions exceed the {actions.MAX_ACTIONS} '
        'the core tracks; remove some actions'
    )


def test_generate_returns_the_emitted_fragments(tmp_path):
    loaded, resolved, repository = load_actions(tmp_path)
    table = build_loaded(loaded, resolved, repository)

    assert actions.generate(loaded, resolved, repository) == (
        actions.emit_h(table),
        actions.emit_c(table),
    )


def test_the_action_fragments_match_the_golden_pair(tmp_path):
    loaded, resolved, repository = load_actions(tmp_path)
    table = build_loaded(loaded, resolved, repository)

    assert actions.emit_h(table) == (GOLDEN / 'actions.h').read_text(encoding='utf-8')
    assert actions.emit_c(table) == (GOLDEN / 'actions.c').read_text(encoding='utf-8')


@pytest.mark.skipif(shutil.which('gcc') is None, reason='no host C compiler')
def test_the_action_table_is_c99(tmp_path):
    loaded, resolved, repository = load_actions(tmp_path)
    table = build_loaded(loaded, resolved, repository)
    header = tmp_path / 'r2s_actions_gen.h'
    source = tmp_path / 'r2s_actions_gen.c'
    header.write_text(
        '#ifndef R2S_ACTIONS_GEN_H\n#define R2S_ACTIONS_GEN_H\n'
        '#include "r2s/r2s_actions.h"\n' + actions.emit_h(table) + '\n#endif\n',
        encoding='utf-8',
    )
    source.write_text(
        '#include "r2s_actions_gen.h"\n' + actions.emit_c(table) + '\n', encoding='utf-8'
    )
    compiled = subprocess.run(
        [
            'gcc',
            '-std=c99',
            '-Wall',
            '-Wextra',
            '-Werror',
            f'-I{CORE_INCLUDE}',
            f'-I{tmp_path}',
            '-DR2S_WITH_ACTIONS',
            '-c',
            str(source),
            '-o',
            str(tmp_path / 'r2s_actions_gen.o'),
        ],
        capture_output=True,
        text=True,
        check=False,
    )
    assert compiled.returncode == 0, compiled.stderr
