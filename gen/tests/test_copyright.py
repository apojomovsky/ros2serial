"""
Copyright checks for the generator, run only by the advisory lint job.

The golden files keep their own Generated by notice instead of the SPDX
header, so the scan excludes them, along with the build's staging copies
of the generated tree (see #511). The tree carries the SPDX two-liner by
decision (#549), which ament_copyright cannot read: it only accepts its
fixed MIT permission text and reports license=<unknown>. The advisory job
records that count instead of failing on it.
"""

import os
from pathlib import Path

import pytest


def generated_copies() -> list[str]:
    """Return the staged and built copies of the generated tree, when present."""
    here = Path(__file__).resolve().parent
    roots = [here / 'golden', here.parent / 'cpp_stage', here.parent / 'build']
    return sorted(
        str(p) for root in roots if root.is_dir() for p in root.rglob('*') if p.is_file()
    )


@pytest.mark.copyright
@pytest.mark.linter
def test_copyright():
    if os.environ.get('R2S_AMENT_LINT') != '1':
        pytest.skip('the ament linters run only in the advisory CI job')
    from ament_copyright.main import main

    rc = main(argv=['--exclude', *generated_copies()])
    assert rc == 0, 'Found errors'
