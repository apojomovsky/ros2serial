def _runtime_check(library: Library) -> list[str]:
    """
    Emit the frame check the runtime route compiles.

    That route compiles no X-macro rows, so the row check never runs there.
    It names its types in `Publisher<T>` and `Subscription<T>` instead, and a
    `constexpr` over the library is what a build can check without the
    generator. The limit itself stays a build flag, since the core's
    translation units never see this header. The two maxima are independent:
    the largest payload and the longest type name need not belong to the same
    type, and a topic name arrives at run time, so the check bounds it by the
    frame it must fit.
    """
    sizes = payload_sizes(library)
    largest = max(sizes.items(), key=lambda item: (item[1], item[0]))
    longest = max(sizes, key=len)
    return [
        '',
        '/* The runtime route compiles no X-macro rows, so no row check runs',
        ' * here. The largest payload a carried type produces, and the longest',
        ' * announce, must still fit the limit the build compiled at. */',
        'namespace r2s',
        '{',
        'namespace detail',
        '{',
        f'constexpr uint16_t frame_largest_payload = {largest[1]}u;',
        f'constexpr uint16_t frame_longest_type_name = {len(longest)}u;',
        'constexpr uint16_t frame_varint_len(uint16_t n)',
        '{',
        '  return n < 128u ? 1u : (n < 16384u ? 2u : 3u);',
        '}',
        'template<uint16_t FrameLimit>',
        'struct frame_fits',
        '{',
        '  static_assert(',
        '    FrameLimit >= frame_largest_payload + 4u,',
        f'    "R2S_MAX_FRAME is below the {largest[1]} bytes {largest[0]} encodes");',
        '  static_assert(',
        '    FrameLimit >= 12u + frame_varint_len(frame_longest_type_name)',
        '      + frame_longest_type_name + 4u,',
        f'    "R2S_MAX_FRAME is below the frame announcing {longest}");',
        '  typedef char ok;',
        '};',
        '} // namespace detail',
        '} // namespace r2s',
        '',
        '/* Naming the type instantiates the template, which is what fails the build. */',
        'typedef r2s::detail::frame_fits<R2S_MAX_FRAME>::ok r2s_frame_check;',
        '',
    ]


def _wrapped_define(head: str, value: str) -> list[str]:
    """
    Wrap a #define the way uncrustify keeps it.

    A comma list rides on one line within 88 columns, else the whole value
    rides on its own line, as does any other value past 100 columns.
    """
    if ',' in value:
        if len(f'{head} {value}') <= 88:
            return [f'{head} {value}']
        return [f'{head} \\', f'  {value}']
    if len(f'{head} {value}') <= 100:
        return [f'{head} {value}']
    return [f'{head} \\', f'  {value}']


def _scope_maps(
    library: Library,
    tables: Mapping[str, descriptors.DescriptorTable],
) -> list[str]:
    """
    Emit one scope map per package: the facts a sketch row needs about its type.

    A row names a C++ type (`pkg::msg::Type`), which the preprocessor cannot
    split into package and type, so each row pastes only the package half and
    the trailing `::msg::Type` resolves the entity through scope lookup. The
    hash travels as eight separate bytes, since an array member needs eight
    initializers and only one entity resolves per paste.
    """
    sizes = payload_sizes(library)
    by_package: dict[tuple[str, str], list[tuple[str, str, int]]] = {}
    for name in library.types:
        package, kind, short = _kind(name)
        by_package.setdefault((package, kind), []).append(
            (short, _cname(name), tables[name].index_of[name])
        )
    lines = [
        '/* One scope map per package: a row names a C++ type, which the',
        ' * preprocessor cannot split, so the row pastes the package half and',
        ' * the trailing ::msg::Type resolves the entity it needs. */',
    ]
    for (package, kind), entries in by_package.items():
        lines += [f'namespace R2S_MAP_{package}', '{', f'namespace {kind}', '{']
        for short, cname, index in entries:
            canonical = f'{package}/{kind}/{short}'
            lines.append(f'/* {cpp.cpp_type(canonical)}: hash, table, index and wire name. */')
            for byte_index, byte in enumerate(
                _hash_bytes(library.repository, canonical).split(', ')
            ):
                lines.append(f'constexpr uint8_t {short}_hash_{byte_index} = {byte};')
            table_line = (
                f'constexpr const r2s_codec_table_t *{short}_table = &r2s_bundled_table_{cname};'
            )
            if len(table_line) <= 100:
                lines.append(table_line)
            else:
                lines.append(f'constexpr const r2s_codec_table_t *{short}_table =')
                lines.append(f'  &r2s_bundled_table_{cname};')
            lines.append(f'constexpr uint16_t {short}_index = {index}u;')
            lines.append(f'constexpr const char {short}_name[] = "{canonical}";')
            if library.frame_checks:
                lines.append(f'constexpr uint16_t {short}_payload = {sizes[canonical]}u;')
        lines += [f'}} // namespace {kind}', f'}} // namespace R2S_MAP_{package}', '']
    return lines


def _c_type_aliases(
    library: Library,
    tables: Mapping[str, descriptors.DescriptorTable],
) -> list[str]:
    """
    Emit one alias macro per type for the C row spelling.

    A C row spells its type the generated C struct name, which pastes
    straight onto these, so the C expansion never splits the spelling the
    way the C++ scope maps do.
    """
    lines = [
        '/* One alias per bundled type for the C row spelling: the row names',
        ' * the generated C struct, which pastes straight onto these. */',
    ]
    for name in library.types:
        package, kind, short = _kind(name)
        ctype = f'{package}__{kind}__{short}'
        cname = _cname(name)
        index = tables[name].index_of[name]
        lines.append(f'/* {ctype}: hash, table, index and wire name. */')
        lines.extend(
            _wrapped_define(
                f'#define R2S_CTYPE_HASH_{ctype}', _hash_bytes(library.repository, name)
            )
        )
        lines.extend(
            _wrapped_define(f'#define R2S_CTYPE_TABLE_{ctype}', f'(&r2s_bundled_table_{cname})')
        )
        lines.extend(_wrapped_define(f'#define R2S_CTYPE_INDEX_{ctype}', f'{index}u'))
        lines.extend(_wrapped_define(f'#define R2S_CTYPE_NAME_{ctype}', f'"{name}"'))
    return lines


def _c_spelling_traps(library: Library) -> list[str]:
    """
    Emit one trap per package and lookup for a C row with a C++ spelling.

    A C row that spells its type with double colons pastes only the package
    half here, so it fails naming the underscore spelling the C list uses.
    """
    lines = [
        '/* A C row that spells its type with double colons pastes only the',
        ' * package half here, and fails naming the underscore spelling. */',
    ]
    for package in sorted({_kind(name)[0] for name in library.types}):
        for kind in ('HASH', 'TABLE', 'INDEX', 'NAME'):
            lines.append(
                f'#define R2S_CTYPE_{kind}_{package} R2S_error_expected_c_row_pkg__msg__Type'
            )
    return lines


def _cxx_spelling_traps(library: Library) -> list[str]:
    """
    Emit one trap per bundled type and lookup for a C++ row with a C spelling.

    A C++ row that spells its type with underscores selects one of these
    instead of the scope maps above, and fails naming the double-colon
    spelling the C++ list uses.
    """
    lines = [
        '/* A C++ row that spells its type with underscores selects one of',
        ' * these instead of the scope maps above, and fails naming the',
        ' * double-colon spelling. */',
    ]
    for name in library.types:
        package, kind, short = _kind(name)
        key = f'{package}__{kind}__{short}'
        for entity in [f'hash_{byte}' for byte in range(8)] + ['table', 'index', 'name']:
            lines.extend(
                _wrapped_define(
                    f'#define R2S_MAP_{key}_{entity}',
                    'R2S_error_cxx_rows_use_double_colon_not_underscores',
                )
            )
    return lines


