"""C emission: the message structs a firmware includes.

Descriptors and the topic table come with later tickets, so this module only
turns resolved types into C99 structs, a type always before the types that use it.
"""

from __future__ import annotations

from collections.abc import Mapping

from r2s_gen.bounds import ResolvedField, ResolvedMessage
from r2s_gen.version import __version__

INDENT = "    "

_ONE_BYTE = frozenset({"bool", "byte", "char", "uint8", "int8"})

_SCALARS = {
    "bool": "uint8_t",
    "byte": "uint8_t",
    "char": "uint8_t",
    "int8": "int8_t",
    "uint8": "uint8_t",
    "int16": "int16_t",
    "uint16": "uint16_t",
    "int32": "int32_t",
    "uint32": "uint32_t",
    "int64": "int64_t",
    "uint64": "uint64_t",
    "float32": "float",
    "float64": "double",
}


def emit_types(resolved: Mapping[str, ResolvedMessage]) -> str:
    """The generated header holding every type in `resolved`, dependencies first.

    Fields must be resolved and bounded, which `bounds.resolve` guarantees; the
    output depends only on the data, not on the mapping's order.
    """
    lines = [
        f"/* Generated by r2s-gen {__version__} from the resolved message types; do not edit. */",
        "#ifndef R2S_GENERATED_H",
        "#define R2S_GENERATED_H",
        "",
        "#include <stdint.h>",
    ]
    for type_name in _ordered(resolved):
        lines.append("")
        lines.extend(_struct(resolved[type_name], resolved))
    lines.extend(["", "#endif", ""])
    return "\n".join(lines)


def _ordered(resolved: Mapping[str, ResolvedMessage]) -> list[str]:
    """Every type once, each after the nested types its fields use; ties by name."""
    ordered: list[str] = []
    defined: set[str] = set()

    def visit(type_name: str) -> None:
        if type_name in defined:
            return
        for field in resolved[type_name].fields:
            if field.type_name in resolved:
                visit(field.type_name)
        defined.add(type_name)
        ordered.append(type_name)

    for type_name in sorted(resolved):
        visit(type_name)
    return ordered


def _struct(message: ResolvedMessage, resolved: Mapping[str, ResolvedMessage]) -> list[str]:
    name = _c_name(message.type_name)
    lines = [f"typedef struct {name} {{"]
    for field in message.fields:
        lines.extend(_field(field, resolved))
    if not message.fields:
        # C99 has no empty struct, and an empty .msg is valid.
        lines.append(f"{INDENT}uint8_t structure_needs_at_least_one_member;")
    lines.append(f"}} {name};")
    return lines


def _field(field: ResolvedField, resolved: Mapping[str, ResolvedMessage]) -> list[str]:
    string = field.type_name == "string"
    elements = _element(field)
    if not field.is_array:
        if string:
            return [f"{INDENT}char {field.name}[{field.string_bound + 1}];"]
        return [f"{INDENT}{elements} {field.name};"]
    count = field.array_bound
    if not field.is_sequence:
        if string:
            return [f"{INDENT}char {field.name}[{count}][{field.string_bound + 1}];"]
        return [f"{INDENT}{elements} {field.name}[{count}];"]
    # A sequence carries its own count; the element type decides the width.
    counter = "uint8_t" if count <= 255 else "uint16_t"
    lines = [f"{INDENT}struct {{"]
    if string:
        lines.append(f"{INDENT * 2}char data[{count}][{field.string_bound + 1}];")
    else:
        lines.append(f"{INDENT * 2}{elements} data[{count}];")
    # [DSC-20] puts the count at a multiple of its width from the field start,
    # so a two-byte count needs the byte a weaker-alignment target would omit.
    if counter == "uint16_t" and _odd_elements(field, resolved):
        lines.append(f"{INDENT * 2}uint8_t _pad;")
    lines.append(f"{INDENT * 2}{counter} size;")
    lines.append(f"{INDENT}}} {field.name};")
    return lines


def _odd_elements(field: ResolvedField, resolved: Mapping[str, ResolvedMessage]) -> bool:
    """Whether `count` elements of the field's type take an odd number of bytes."""
    return bool((field.array_bound % 2) and _element_parity(field, resolved))


def _element_parity(field: ResolvedField, resolved: Mapping[str, ResolvedMessage]) -> int:
    """1 when one element of the field's type takes an odd number of bytes."""
    if field.type_name == "string":
        return (field.string_bound + 1) % 2
    if field.type_name in _ONE_BYTE:
        return 1
    if field.type_name in _SCALARS:
        return 0
    return _message_parity(resolved[field.type_name], resolved)


def _message_parity(message: ResolvedMessage, resolved: Mapping[str, ResolvedMessage]) -> int:
    """1 when the emitted struct's packed storage takes an odd number of bytes."""
    if not message.fields:
        return 1
    parity = 0
    for field in message.fields:
        parity ^= _storage_parity(field, resolved)
    return parity


def _storage_parity(field: ResolvedField, resolved: Mapping[str, ResolvedMessage]) -> int:
    elements = _element_parity(field, resolved)
    if not field.is_array:
        return elements
    if not field.is_sequence:
        return elements if field.array_bound % 2 else 0
    if field.array_bound > 255:
        return 0
    return (elements * field.array_bound + 1) % 2


def _element(field: ResolvedField) -> str:
    if field.type_name == "string":
        return f"char[{field.string_bound + 1}]"
    if field.type_name in _SCALARS:
        return _SCALARS[field.type_name]
    return _c_name(field.type_name)


def _c_name(type_name: str) -> str:
    """A canonical `package/msg/Type` as the rosidl C identifier `package__msg__Type`."""
    package, _, name = type_name.partition("/msg/")
    return f"{package}__msg__{name}"
