"""C emission: the message structs a firmware includes.

Descriptors and the topic table come with later tickets, so this module only
turns resolved types into C99 structs, a type always before the types that use it.
"""

from __future__ import annotations

from collections.abc import Mapping

from r2s_gen.bounds import ResolvedField, ResolvedMessage
from r2s_gen.version import __version__

INDENT = "    "

_SCALARS = {
    "bool": "uint8_t",
    "byte": "uint8_t",
    "char": "uint8_t",
    "int8": "int8_t",
    "uint8": "uint8_t",
    "int16": "int16_t",
    "uint16": "uint16_t",
    "int32": "int32_t",
    "uint32": "uint32_t",
    "int64": "int64_t",
    "uint64": "uint64_t",
    "float32": "float",
    "float64": "double",
}

_ALIGNMENT_PROBE = """typedef struct {
    uint8_t byte;
    uint16_t following;
} r2s_generated_count_alignment_t;

#define R2S_COUNT_ALIGNMENT offsetof(r2s_generated_count_alignment_t, following)

#define R2S_ROUND_UP(value, alignment) (((value) + (alignment) - 1) / (alignment) * (alignment))

/* A count member sits where the compiler aligns a member that follows the
 * elements ([DSC-20]); the check below fails the build when it does not. */
#define R2S_COUNT_CHECK(owner, field, count, alignment)                                                      \\
    typedef char                                                                                             \\
        r2s_count_check_##owner##__##field[((offsetof(owner, field.size) - offsetof(owner, field.data)) ==   \\
                                            R2S_ROUND_UP((count) * sizeof(((owner *)0)->field.data[0]),      \\
                                                         (alignment)))                                       \\
                                               ? 1                                                           \\
                                               : -1]"""


def emit_types(resolved: Mapping[str, ResolvedMessage], max_nest: int | None = None) -> str:
    """The generated header holding every type in `resolved`, dependencies first.

    Fields must be resolved and bounded, which `bounds.resolve` guarantees; the
    output depends only on the data, not on the mapping's order. A given
    `max_nest` also configures the codec's nesting stack ([DSC-39]).
    """
    sequenced = _has_sequences(resolved)
    includes = ["#include <stddef.h>", "#include <stdint.h>"] if sequenced else ["#include <stdint.h>"]
    lines = [
        f"/* Generated by r2s-gen {__version__} from the resolved message types; do not edit. */",
        "#ifndef R2S_GENERATED_H",
        "#define R2S_GENERATED_H",
        "",
        *includes,
    ]
    if max_nest is not None:
        lines.extend(
            [
                "",
                "/* The deepest nesting the firmware's tables use; the codec sizes its",
                " * stack from it, and a build that sets it first keeps its value. */",
                "#ifndef R2S_MAX_NEST",
                f"#define R2S_MAX_NEST {max_nest}u",
                "#endif",
            ]
        )
    if sequenced:
        lines.extend(["", *_ALIGNMENT_PROBE.splitlines()])
    for type_name in _ordered(resolved):
        message = resolved[type_name]
        lines.append("")
        lines.extend(_struct(message))
        checks = _checks(message)
        if checks:
            lines.extend(["", *checks])
    lines.extend(["", "#endif", ""])
    return "\n".join(lines)


def _has_sequences(resolved: Mapping[str, ResolvedMessage]) -> bool:
    return any(field.is_sequence for message in resolved.values() for field in message.fields)


def _ordered(resolved: Mapping[str, ResolvedMessage]) -> list[str]:
    """Every type once, each after the nested types its fields use; ties by name."""
    ordered: list[str] = []
    defined: set[str] = set()

    def visit(type_name: str) -> None:
        if type_name in defined:
            return
        for field in resolved[type_name].fields:
            if field.type_name in resolved:
                visit(field.type_name)
        defined.add(type_name)
        ordered.append(type_name)

    for type_name in sorted(resolved):
        visit(type_name)
    return ordered


def _struct(message: ResolvedMessage) -> list[str]:
    name = _c_name(message.type_name)
    lines = [f"typedef struct {name} {{"]
    for field in message.fields:
        lines.extend(_field(field))
    if not message.fields:
        # C99 has no empty struct, and an empty .msg is valid.
        lines.append(f"{INDENT}uint8_t structure_needs_at_least_one_member;")
    lines.append(f"}} {name};")
    return lines


def _checks(message: ResolvedMessage) -> list[str]:
    owner = _c_name(message.type_name)
    return [
        f"R2S_COUNT_CHECK({owner}, {field.name}, {field.array_bound}, "
        f"{'1' if field.array_bound <= 255 else 'R2S_COUNT_ALIGNMENT'});"
        for field in message.fields
        if field.is_sequence
    ]


def _field(field: ResolvedField) -> list[str]:
    string = field.type_name == "string"
    elements = _element(field)
    if not field.is_array:
        if string:
            return [f"{INDENT}char {field.name}[{field.string_bound + 1}];"]
        return [f"{INDENT}{elements} {field.name};"]
    count = field.array_bound
    if not field.is_sequence:
        if string:
            return [f"{INDENT}char {field.name}[{count}][{field.string_bound + 1}];"]
        return [f"{INDENT}{elements} {field.name}[{count}];"]
    lines = [f"{INDENT}struct {{"]
    if string:
        lines.append(f"{INDENT * 2}char data[{count}][{field.string_bound + 1}];")
    else:
        lines.append(f"{INDENT * 2}{elements} data[{count}];")
    lines.append(f"{INDENT * 2}{'uint8_t' if count <= 255 else 'uint16_t'} size;")
    lines.append(f"{INDENT}}} {field.name};")
    return lines


def _element(field: ResolvedField) -> str:
    if field.type_name == "string":
        return f"char[{field.string_bound + 1}]"
    if field.type_name in _SCALARS:
        return _SCALARS[field.type_name]
    return _c_name(field.type_name)


def _c_name(type_name: str) -> str:
    """A canonical `package/msg/Type` as the rosidl C identifier `package__msg__Type`."""
    package, _, name = type_name.partition("/msg/")
    return f"{package}__msg__{name}"
