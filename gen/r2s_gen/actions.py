"""The `actions` section: the action table the firmware announces.

An action entry names one ROS action the MCU serves, the goal, feedback
and result descriptor indices the depth-first walk fixed, and the first 8
bytes of the action's RIHS01 hash (spec/protocol.md, 7.9).
"""

from collections.abc import Mapping
from dataclasses import dataclass

from r2s_gen import bounds
from r2s_gen import descriptors
from r2s_gen import msgs
from r2s_gen import topics
from r2s_gen import typehash
from r2s_gen.config import Config
from r2s_gen.msgs import MessageError
from r2s_gen.msgs import MessageRepository
from r2s_gen.version import __version__

MAX_ACTIONS = 4


@dataclass(frozen=True)
class ActionEntry:
    name: str
    type_name: str
    c_name: str
    action_id: int
    type_index_goal: int
    type_index_feedback: int
    type_index_result: int
    type_hash: bytes


@dataclass(frozen=True)
class ActionTable:
    node: str
    entries: tuple[ActionEntry, ...]


def roots(loaded: Config) -> list[str]:
    """Return the descriptor roots one action section needs: its goals, feedbacks and results."""
    names: list[str] = []
    for action in loaded.actions:
        canonical = msgs.canonical_type_name(action.type_name)
        names.extend([f'{canonical}_Goal', f'{canonical}_Feedback', f'{canonical}_Result'])
    return names


def build(
    loaded: Config,
    resolved: Mapping[str, bounds.ResolvedMessage],
    repository: MessageRepository,
    table: descriptors.DescriptorTable | None = None,
    source: str = 'r2s.yaml',
) -> ActionTable:
    """Build the action table for `config`: IDs, hashes and descriptor indices."""
    if len(loaded.actions) > MAX_ACTIONS:
        raise MessageError(
            f'{source}: actions',
            f'{len(loaded.actions)} actions exceed the {MAX_ACTIONS} the core tracks',
            'remove some actions',
        )
    if table is None:
        table = descriptors.build(resolved, roots(loaded))
    entries = tuple(
        ActionEntry(
            name=action.name,
            type_name=msgs.canonical_type_name(action.type_name),
            c_name=topics.c_identifier(action.name),
            action_id=position,
            type_index_goal=table.index_of[f'{msgs.canonical_type_name(action.type_name)}_Goal'],
            type_index_feedback=table.index_of[
                f'{msgs.canonical_type_name(action.type_name)}_Feedback'
            ],
            type_index_result=table.index_of[
                f'{msgs.canonical_type_name(action.type_name)}_Result'
            ],
            type_hash=_hash(repository, action.type_name),
        )
        for position, action in enumerate(loaded.actions)
    )
    return ActionTable(node=loaded.node, entries=entries)


def _hash(repository: MessageRepository, type_name: str) -> bytes:
    """Return the first 8 bytes of the action's RIHS01 hash, as ACT-7 carries them."""
    digest = typehash.action_hash(repository, type_name)
    return bytes.fromhex(digest[len('RIHS01_') :])[:8]


def emit_h(table: ActionTable) -> str:
    """Emit the action section of the generated header: the count, the IDs and the table."""
    lines = [
        f'/* Generated by r2s-gen {__version__} from the configured actions; do not edit. */',
        '/* Actions in configuration order: IDs run from 0, each action',
        ' * names its goal, feedback and result by the descriptor indices the',
        ' * depth-first walk fixed (DSC-11). The MCU serves every action it',
        ' * declares (ACT-7). */',
        '',
        f'#define R2S_ACTION_COUNT {len(table.entries)}u',
    ]
    if table.entries:
        lines.extend(
            [
                '#ifndef R2S_ACTION_MAX_COUNT',
                f'#define R2S_ACTION_MAX_COUNT {len(table.entries)}u',
                '#endif',
                '',
                '#include "r2s/r2s_actions.h"',
                '',
            ]
        )
    for entry in table.entries:
        lines.extend(
            topics._define_lines(f'R2S_ACTION_{entry.c_name.upper()}_ID', f'{entry.action_id}u')
        )
    for entry in table.entries:
        lines.extend(
            topics._define_lines(
                f'R2S_ACTION_{entry.c_name.upper()}_GOAL_TYPE',
                f'{entry.type_index_goal}u',
            )
        )
    for entry in table.entries:
        lines.extend(
            topics._define_lines(
                f'R2S_ACTION_{entry.c_name.upper()}_FEEDBACK_TYPE',
                f'{entry.type_index_feedback}u',
            )
        )
    for entry in table.entries:
        lines.extend(
            topics._define_lines(
                f'R2S_ACTION_{entry.c_name.upper()}_RESULT_TYPE',
                f'{entry.type_index_result}u',
            )
        )
    if table.entries:
        lines.extend(
            [
                '',
                '/* The announced actions and the action verdicts (ACT-7); a board',
                ' * that renames actions at launch copies this table. */',
                'extern const r2s_action_t R2S_FLASH r2s_actions[R2S_ACTION_COUNT];',
                '',
            ]
        )
    return '\n'.join(lines)


def emit_c(table: ActionTable) -> str:
    """Emit the action section of the generated source: the announced table."""
    lines = [
        f'/* Generated by r2s-gen {__version__} from the configured actions; do not edit. */',
        '/* The announced actions (ACT-1, ACT-7): the hashes are the first 8 bytes',
        " * of each action's RIHS01 hash, and the goal, feedback and result types are",
        ' * descriptor indices into the shared table. */',
        'const r2s_action_t R2S_FLASH r2s_actions[R2S_ACTION_COUNT] = {',
    ]
    for entry in table.entries:
        digest = ', '.join(f'0x{byte:02x}u' for byte in entry.type_hash)
        lines.extend(
            [
                f'  {{{{{digest}}},',
                *topics._string_row('    ', entry.type_name, ','),
                *topics._string_row('    ', entry.name, '},'),
            ]
        )
    lines.append('};')
    lines.append('')
    return '\n'.join(lines)


def generate(
    loaded: Config,
    resolved: Mapping[str, bounds.ResolvedMessage],
    repository: MessageRepository,
    source: str = 'r2s.yaml',
) -> tuple[str, str]:
    """Generate the firmware's action header and source fragments for `config`."""
    table = build(
        loaded, resolved, repository, descriptors.build(resolved, roots(loaded)), source=source
    )
    return emit_h(table), emit_c(table)
