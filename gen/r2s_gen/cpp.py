"""C++ emission: the per-message headers a C++ sketch includes.

A header carries one message's C++ struct, the checks that tie it to the C
struct the bundle's descriptors describe, and the trait the runtime layer asks
for the type's table, its index and its hash.

The descriptors themselves are not copied here: the trait names the table the
C bundle holds for the type's closure, so the bytes the codec reads are the
ones the C bundle emits, once, in the library.
"""

from __future__ import annotations

import re
from collections.abc import Mapping

from r2s_gen import descriptors
from r2s_gen import emit
from r2s_gen import typehash
from r2s_gen.bounds import ResolvedMessage
from r2s_gen.msgs import MessageRepository
from r2s_gen.version import __version__

INDENT = '  '

# The C bundle's header: the C structs, the limits and the per-type index.
BUNDLED_HEADER = 'r2s_bundled.h'


def _split(type_name: str) -> tuple[str, str, str]:
    if '/action/' in type_name:
        package, _, name = type_name.partition('/action/')
        return package, 'action', name
    package, _, name = type_name.partition('/msg/')
    return package, 'msg', name


def action_name(type_name: str) -> str:
    """A goal, result or feedback type to its action.

    `pkg/action/Name_Goal` to `pkg/action/Name`.
    """
    package, kind, name = _split(type_name)
    if kind != 'action':
        raise ValueError(f'{type_name} is not an action type')
    for suffix_text in ('_Goal', '_Result', '_Feedback'):
        if name.endswith(suffix_text):
            return f'{package}/action/{name[: -len(suffix_text)]}'
    return type_name


def message_path(type_name: str) -> str:
    """A canonical type as the rclcpp header path, actions at `pkg/action/name.hpp`."""
    package, kind, name = _split(type_name)
    if kind == 'action':
        base = (
            action_name(type_name).split('/')[-1] if type_name != action_name(type_name) else name
        )
        return f'{package}/action/{_snake(base)}.hpp'
    return f'{package}/msg/{_snake(name)}.hpp'


def suffix(type_name: str) -> str:
    """A canonical type as the bundle's suffix: `std_msgs/msg/Float32` to `std_msgs_Float32`."""
    package, _, name = _split(type_name)
    return f'{package}_{name}'


def cpp_type(type_name: str) -> str:
    """A canonical type as its C++ name: `std_msgs/msg/Float32` to `std_msgs::msg::Float32`."""
    package, kind, name = _split(type_name)
    return f'{package}::{kind}::{name}'


def _snake(name: str) -> str:
    """A type name as the rclcpp file name spells it: `JointState` to `joint_state`.

    A leading acronym stays one word, as rclcpp spells it: `TFMessage` to
    `tf_message`, not `t_f_message`. The first split breaks before a word
    starting uppercase, the second before an uppercase after lowercase.
    """
    word = re.sub(r'(.)([A-Z][a-z]+)', r'\1_\2', name)
    return re.sub(r'([a-z0-9])([A-Z])', r'\1_\2', word).lower()


def emit_message_hpp(
    resolved: Mapping[str, ResolvedMessage],
    type_name: str,
    repository: MessageRepository,
    distro: str = 'jazzy',
) -> str:
    """The C++ header of one message: its struct, the layout checks and the trait."""
    message = resolved[type_name]
    table = descriptors.build(resolved, [type_name])
    name = suffix(type_name)
    guard = 'R2S_' + re.sub(r'\W', '_', type_name).upper() + '_HPP'
    lines = [
        f'/* Generated by r2s-gen {__version__} from bundle (distro {distro}); do not edit. */',
        f'#ifndef {guard}',
        f'#define {guard}',
        '',
        '#include <stddef.h>',
        '#include <stdint.h>',
        '',
        '#include "r2s/r2s_arch.h"',
        '#include "r2s/r2s_codec.h"',
        '',
        '/* The C structs, the limits and the per-type index the bundle holds:',
        ' * the C++ struct below must hold the same bytes, and the codec reads',
        ' * the offsets from the C ones. */',
        f'#include "{BUNDLED_HEADER}"',
    ]
    nested = sorted(_nested_types(resolved, message))
    if nested:
        lines.append('')
        for other in nested:
            lines.append(f'#include "{message_path(other)}"')
    lines.append('')
    lines.extend(_struct(message))
    lines.append('')
    lines.extend(_layout_checks(message))
    lines.append('')
    lines.extend(_trait(message, name, table, repository))
    lines.extend(['', '#endif', ''])
    return '\n'.join(lines)


def emit_action_hpp(
    resolved: Mapping[str, ResolvedMessage],
    action_name_text: str,
    repository: MessageRepository,
    distro: str = 'jazzy',
) -> str:
    """One action header at the rclcpp path: its goal, result and feedback structs."""
    canonical = action_name_text
    goal_name = f'{canonical}_Goal'
    result_name = f'{canonical}_Result'
    feedback_name = f'{canonical}_Feedback'
    for needed in (goal_name, result_name, feedback_name):
        if needed not in resolved:
            raise ValueError(f'{needed} is not resolved')
    table = descriptors.build(resolved, [goal_name, result_name, feedback_name])
    guard = 'R2S_' + re.sub(r'\W', '_', canonical).upper() + '_HPP'
    lines = [
        f'/* Generated by r2s-gen {__version__} from bundle (distro {distro}); do not edit. */',
        f'#ifndef {guard}',
        f'#define {guard}',
        '',
        '#include <stddef.h>',
        '#include <stdint.h>',
        '',
        '#include "r2s/r2s_arch.h"',
        '#include "r2s/r2s_codec.h"',
        '',
        '/* The C structs, the limits and the per-type index the bundle holds:',
        ' * the C++ structs below must hold the same bytes, and the codec reads',
        ' * the offsets from the C ones. */',
        f'#include "{BUNDLED_HEADER}"',
    ]
    nested: set[str] = set()
    for part in (goal_name, result_name, feedback_name):
        nested |= _nested_types(resolved, resolved[part])
    nested -= {goal_name, result_name, feedback_name}
    if nested:
        lines.append('')
        for other in sorted(nested):
            lines.append(f'#include "{message_path(other)}"')
    for part in (goal_name, result_name, feedback_name):
        lines.append('')
        lines.extend(_struct(resolved[part]))
        lines.append('')
        lines.extend(_layout_checks(resolved[part]))
        lines.append('')
        lines.extend(_trait(resolved[part], suffix(part), table, repository))
    lines.extend(['', '#endif', ''])
    return '\n'.join(lines)


def _nested_types(resolved: Mapping[str, ResolvedMessage], message: ResolvedMessage) -> set[str]:
    """The message types the fields of `message` nest."""
    return {field.type_name for field in message.fields if field.type_name in resolved}


def _struct(message: ResolvedMessage) -> list[str]:
    """The C++ struct of a message, member for member the C struct holds."""
    package, kind, name = _split(message.type_name)
    lines = [
        f'namespace {package}',
        '{',
        f'namespace {kind}',
        '{',
        '',
        f'struct {name}',
        '{',
    ]
    for field in message.fields:
        lines.extend(_field(field))
    if not message.fields:
        # C99 has no empty struct and C++ no empty class, and an empty .msg
        # is valid.
        lines.append(f'{INDENT}uint8_t structure_needs_at_least_one_member;')
    lines.extend(['};', '', f'}} // namespace {kind}', '} // namespace ' + package])
    return lines


def _field(field) -> list[str]:
    """One field as the C emission writes it, with the nested type as its C++ name."""
    if not field.is_sequence:
        return emit.field_members(field, cpp_type)
    lines = [f'{INDENT}struct {field.name}_sequence', f'{INDENT}{{']
    lines.extend(emit.sequence_members(field, cpp_type))
    lines.append(f'{INDENT}}};')
    lines.append(f'{INDENT}{field.name}_sequence {field.name};')
    return lines


def _one_per_line(head: str, args: list, last: str, limit: int = 100) -> list:
    """A check invocation uncrustify keeps: one line within the limit, else
    one argument per line one level past the head."""
    single = f'{head}{", ".join(args)}{last}'
    if len(single) <= limit:
        return [single]
    lines = [f'{head}{args[0]},']
    lines.extend(f'  {arg},' for arg in args[1:-1])
    lines.append(f'  {args[-1]}{last}')
    return lines


def _same_offset(cpp: str, c_name: str, field: str) -> list[str]:
    """A layout check uncrustify keeps: one line within 100 columns,
    otherwise one argument per line."""
    return _one_per_line('R2S_CPP_SAME_OFFSET(', [cpp, c_name, field], ');')


def _same_size(cpp: str, c_name: str) -> list[str]:
    """A size check uncrustify keeps: one line within 100 columns,
    otherwise one argument per line."""
    return _one_per_line('R2S_CPP_SAME_SIZE(', [cpp, c_name], ');')


def _layout_checks(message: ResolvedMessage) -> list[str]:
    """The checks that the C++ struct holds what the C struct the codec writes into holds."""
    c_name = emit._c_name(message.type_name)
    cpp = cpp_type(message.type_name)
    lines = [
        "/* The codec writes into the C struct's bytes at the offsets the",
        ' * descriptors give, so the C++ struct must hold them at the same',
        ' * offsets and the same size. */',
        '#define R2S_CPP_SAME_SIZE(cpp_type, c_type) static_assert(sizeof(cpp_type) '
        '== sizeof(c_type), \\',
        '    #cpp_type)',
        '#define R2S_CPP_SAME_OFFSET(cpp_type, c_type, field) \\',
        '  static_assert(offsetof(cpp_type, field) == offsetof(c_type, field), '
        '#cpp_type "." #field)',
        '',
        *_same_size(cpp, c_name),
    ]
    for field in message.fields:
        lines.extend(_same_offset(cpp, c_name, field.name))
        if field.is_sequence:
            lines.extend(_same_offset(cpp, c_name, f'{field.name}.data'))
            lines.extend(_same_offset(cpp, c_name, f'{field.name}.size'))
    lines.extend(['', '#undef R2S_CPP_SAME_SIZE', '#undef R2S_CPP_SAME_OFFSET'])
    return lines


def _trait(
    message: ResolvedMessage,
    name: str,
    table: descriptors.DescriptorTable,
    repository: MessageRepository,
) -> list[str]:
    """The trait the runtime layer asks for a type's table, index, name and hash."""
    type_name = message.type_name
    index = table.index_of[type_name]
    hash_text = ', '.join(f'0x{byte:02x}u' for byte in hash_bytes(repository, type_name))
    return [
        'namespace r2s',
        '{',
        '',
        "/* The table the C bundle holds for this type's closure: the bytes the",
        ' * codec reads are the ones the C bundle emits. */',
        'extern "C" {',
        f'extern const r2s_codec_table_t r2s_bundled_table_{name};',
        '}',
        '',
        '/* The primary template the runtime layer declares; a message header',
        ' * specializes it, so a sketch names a type and never a table. */',
        'template<typename T>',
        'struct msg_traits;',
        '',
        'template<>',
        f'struct msg_traits<{cpp_type(type_name)}>',
        '{',
        '  static const r2s_codec_table_t * table()',
        '  {',
        f'    return &r2s_bundled_table_{name};',
        '  }',
        '',
        '  static uint16_t type_index()',
        '  {',
        f'    return {index}u;',
        '  }',
        '',
        '  static const char * type_name()',
        '  {',
        f'    return "{type_name}";',
        '  }',
        '',
        '  static const uint8_t * type_hash()',
        '  {',
        f'    static const uint8_t hash[] = {{{hash_text}}};',
        '    return hash;',
        '  }',
        '};',
        '',
        '} // namespace r2s',
    ]


def hash_bytes(repository: MessageRepository, type_name: str) -> bytes:
    """The first 8 bytes of the type's RIHS01 hash, as the topic table announces them."""
    digest = typehash.type_hash(repository, type_name)
    return bytes.fromhex(digest[len('RIHS01_') :])[:8]
