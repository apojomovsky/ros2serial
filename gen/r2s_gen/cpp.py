"""C++ emission: the per-message headers a C++ sketch includes.

A header carries one message's C++ struct, the checks that tie it to the C
struct the bundle's descriptors describe, and the trait the runtime layer asks
for the type's table, its index and its hash.

The descriptors themselves are not copied here: the trait names the table the
C bundle holds for the type's closure, so the bytes the codec reads are the
ones the C bundle emits, once, in the library.
"""

from __future__ import annotations

import re
from collections.abc import Mapping

from r2s_gen import descriptors, emit, typehash
from r2s_gen.bounds import ResolvedMessage
from r2s_gen.msgs import MessageRepository
from r2s_gen.version import __version__

INDENT = "    "

# The C bundle's header: the C structs, the limits and the per-type index.
BUNDLED_HEADER = "r2s_bundled.h"


def message_path(type_name: str) -> str:
    """A canonical type as the rclcpp header path: `std_msgs/msg/Float32` to `std_msgs/msg/float32.hpp`."""
    package, _, name = type_name.partition("/msg/")
    return f"{package}/msg/{_snake(name)}.hpp"


def suffix(type_name: str) -> str:
    """A canonical type as the bundle's suffix: `std_msgs/msg/Float32` to `std_msgs_Float32`."""
    package, _, name = type_name.partition("/msg/")
    return f"{package}_{name}"


def cpp_type(type_name: str) -> str:
    """A canonical type as its C++ name: `std_msgs/msg/Float32` to `std_msgs::msg::Float32`."""
    package, _, name = type_name.partition("/msg/")
    return f"{package}::msg::{name}"


def _snake(name: str) -> str:
    """A type name as the rclcpp file name spells it: `JointState` to `joint_state`."""
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()


def emit_message_hpp(
    resolved: Mapping[str, ResolvedMessage],
    type_name: str,
    repository: MessageRepository,
    distro: str = "jazzy",
    digest: str = "",
) -> str:
    """The C++ header of one message: its struct, the layout checks and the trait."""
    message = resolved[type_name]
    table = descriptors.build(resolved, [type_name])
    name = suffix(type_name)
    guard = "R2S_" + re.sub(r"\W", "_", type_name).upper() + "_HPP"
    lines = [
        f"/* Generated by r2s-gen {__version__} from bundle (distro {distro}, bundle {digest}); do not edit. */",
        f"#ifndef {guard}",
        f"#define {guard}",
        "",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
        '#include "r2s/r2s_arch.h"',
        '#include "r2s/r2s_codec.h"',
        "",
        "/* The C structs, the limits and the per-type index the bundle holds:",
        " * the C++ struct below must hold the same bytes, and the codec reads",
        " * the offsets from the C ones. */",
        f'#include "{BUNDLED_HEADER}"',
    ]
    nested = sorted(_nested_types(resolved, message))
    if nested:
        lines.append("")
        for other in nested:
            lines.append(f'#include "{message_path(other)}"')
    lines.append("")
    lines.extend(_struct(message))
    lines.append("")
    lines.extend(_layout_checks(message))
    lines.append("")
    lines.extend(_trait(message, name, table, repository))
    lines.extend(["", "#endif", ""])
    return "\n".join(lines)


def _nested_types(resolved: Mapping[str, ResolvedMessage], message: ResolvedMessage) -> set[str]:
    """The message types the fields of `message` nest."""
    return {field.type_name for field in message.fields if field.type_name in resolved}


def _struct(message: ResolvedMessage) -> list[str]:
    """The C++ struct of a message, member for member the C struct holds."""
    package, _, name = message.type_name.partition("/msg/")
    lines = [
        f"namespace {package}",
        "{",
        "namespace msg",
        "{",
        "",
        f"struct {name} {{",
    ]
    for field in message.fields:
        lines.extend(_field(field))
    if not message.fields:
        # C99 has no empty struct and C++ no empty class, and an empty .msg
        # is valid.
        lines.append(f"{INDENT}uint8_t structure_needs_at_least_one_member;")
    lines.extend(["};", "", "} // namespace msg", "} // namespace " + package])
    return lines


def _field(field) -> list[str]:
    """One field as the C emission writes it, with the nested type as its C++ name."""
    if not field.is_sequence:
        return emit.field_members(field, cpp_type)
    lines = [f"{INDENT}struct {field.name}_sequence {{"]
    lines.extend(emit.sequence_members(field, cpp_type))
    lines.append(f"{INDENT}}};")
    lines.append(f"{INDENT}{field.name}_sequence {field.name};")
    return lines


def _cont(line: str) -> str:
    """A macro continuation line padded to the column clang-format aligns backslashes to."""
    return line.ljust(109) + "\\"


def _layout_checks(message: ResolvedMessage) -> list[str]:
    """The checks that the C++ struct holds what the C struct the codec writes into holds."""
    c_name = emit._c_name(message.type_name)
    cpp = cpp_type(message.type_name)
    lines = [
        "/* The codec writes into the C struct's bytes at the offsets the",
        " * descriptors give, so the C++ struct must hold them at the same",
        " * offsets and the same size. */",
        "#define R2S_CPP_SAME_SIZE(cpp_type, c_type) static_assert(sizeof(cpp_type) == sizeof(c_type), #cpp_type)",
        _cont("#define R2S_CPP_SAME_OFFSET(cpp_type, c_type, field)"),
        '    static_assert(offsetof(cpp_type, field) == offsetof(c_type, field), #cpp_type "." #field)',
        "",
        f"R2S_CPP_SAME_SIZE({cpp}, {c_name});",
    ]
    for field in message.fields:
        lines.append(f"R2S_CPP_SAME_OFFSET({cpp}, {c_name}, {field.name});")
        if field.is_sequence:
            lines.append(f"R2S_CPP_SAME_OFFSET({cpp}, {c_name}, {field.name}.data);")
            lines.append(f"R2S_CPP_SAME_OFFSET({cpp}, {c_name}, {field.name}.size);")
    lines.extend(["", "#undef R2S_CPP_SAME_SIZE", "#undef R2S_CPP_SAME_OFFSET"])
    return lines


def _trait(
    message: ResolvedMessage,
    name: str,
    table: descriptors.DescriptorTable,
    repository: MessageRepository,
) -> list[str]:
    """The trait the runtime layer asks for a type's table, index, name and hash."""
    type_name = message.type_name
    index = table.index_of[type_name]
    hash_text = ", ".join(f"0x{byte:02x}u" for byte in hash_bytes(repository, type_name))
    return [
        "namespace r2s",
        "{",
        "",
        "/* The table the C bundle holds for this type's closure: the bytes the",
        " * codec reads are the ones the C bundle emits. */",
        'extern "C" {',
        f"extern const r2s_codec_table_t r2s_bundled_table_{name};",
        "}",
        "",
        "/* The primary template the runtime layer declares; a message header",
        " * specializes it, so a sketch names a type and never a table. */",
        "template <typename T> struct msg_traits;",
        "",
        f"template <> struct msg_traits<{cpp_type(type_name)}> {{",
        "    static const r2s_codec_table_t *table()",
        "    {",
        f"        return &r2s_bundled_table_{name};",
        "    }",
        "",
        "    static uint16_t type_index()",
        "    {",
        f"        return {index}u;",
        "    }",
        "",
        "    static const char *type_name()",
        "    {",
        f'        return "{type_name}";',
        "    }",
        "",
        "    static const uint8_t *type_hash()",
        "    {",
        f"        static const uint8_t hash[] = {{{hash_text}}};",
        "        return hash;",
        "    }",
        "};",
        "",
        "} // namespace r2s",
    ]


def hash_bytes(repository: MessageRepository, type_name: str) -> bytes:
    """The first 8 bytes of the type's RIHS01 hash, as the topic table announces them."""
    digest = typehash.type_hash(repository, type_name)
    return bytes.fromhex(digest[len("RIHS01_") :])[:8]
