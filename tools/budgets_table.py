"""The published budgets page: docs/budgets.md, generated from measurements.

render_page combines the flash and RAM measurements, the static stack
analysis and tools/budgets.yaml into one table per example and board,
plus the method and the trade-offs the budgets encode. The budgets job
renders the same page from its own numbers and fails when the checked-in
copy differs, so the table cannot drift from what the tools measure.
"""

import argparse
import json
import sys
from pathlib import Path

import size_report

GENERATED_NOTE = (
    '<!-- DO NOT EDIT: generated by tools/budgets_table.py from the measured'
    ' firmware and tools/budgets.yaml. Refresh with make size-report. -->'
)

METHOD = """## How to reproduce

Run `make size-report` in the dev image. It builds every example sketch
for Uno and Mega through `scripts/build-examples.sh`, the ESP32 builds
through `scripts/build-examples-esp32.sh`, the STM32 firmware through
`ports/stm32/build.sh` and the RP2040 firmware through
`ports/rp2040/build.sh`, then measures the firmware
with `tools/size_report.py` and `tools/stack_report.py`:

* Flash is text plus data and static RAM is data plus bss, as `avr-size`
  prints them. ESP32 firmware measures through the matching
  `xtensa-esp32-elf-size`, and STM32 and RP2040 firmware through
  `arm-none-eabi-size`, whose tables read the same way.
* The stack column is the deepest static path from `main`, computed from
  `avr-gcc -fstack-usage` frames and the `avr-objdump -d` call graph.
  The core allows no recursion and no indirect calls, so the deepest
  path is the worst case. The shipped firmware uses link-time
  optimization, under which `avr-gcc` writes no frame files, so the gate
  rebuilds each sketch without LTO under `stack/` and analyzes that
  build; the deeper non-LTO paths overestimate rather than hide.
  Xtensa and Arm firmware skip the AVR call-graph analysis, so ESP32,
  STM32 and RP2040 rows read `n/a` for stack.
* The toolchain is pinned in `ci/versions.env`, so the same image
  measures the same bytes everywhere, including CI.

The budgets job judges every pull request by these numbers: a change
that pushes flash, RAM or stack past `tools/budgets.yaml` fails, and a
change that moves a number within budget reports its delta against the
base in the job summary.
"""

TRADE_OFFS = """## What the budgets encode

Each budget is a promise that a feature earns its bytes on an Uno with
2 KB of RAM (the Mega carries the same firmware with 8 KB of headroom):

* The table-driven CRC stays out. It would roughly halve framing plus
  check cost on CRC-heavy frames for 498 bytes of flash, so it remains
  an option for its own ticket, not part of the shipped firmware. See
  `docs/benchmarks/framing-crc.md`.
* Narrowing stays per topic, not per field. Per-field narrowing would
  save 40 bytes on one mixed message while adding descriptor flags and
  bridge conversion for every message; per-topic narrow already takes
  the full saving everywhere. See `docs/benchmarks/encoding-packed-vs-cdr-vs-mavlink.md`.
* The runtime topic table is sized for the worst case the build allows,
  so the marginal cost of a topic is one 14-byte entry on an
  ATmega328P, while the total grows with the topic limit, not with the
  sketch. Static sketches link no runtime table at all and keep that
  RAM: compare `arduino_static` against the runtime sketches below.
* The action sketch fits beside the runtime by capping its frames at
  128 bytes and exchanging Float32 only, leaving room for the retry
  buffers the reliable channel needs.
* The stack budget holds because the core never recurses and never
  calls through a pointer, which the zone check enforces; the analysis
  above proves the bound instead of hoping the harness reached it.

## Performance

Encoding stays out of the link's way: even the hottest message costs
under a third of the cycles its bytes occupy on the wire at 115200
baud, and `tools/test_encoding_benchmark.py` pins that ratio as a 400
cycles per byte tripwire rather than pinning exact counts. The framing
choice is measured the same way in `docs/benchmarks/framing-crc.md`.
These tests are the performance budgets, and they fail the suite when
the code outgrows them.
"""


def render_table(measurements: dict, stacks: dict, budgets: dict) -> str:
    """One row per measured firmware: measured numbers beside their budgets."""
    rows = [
        '| firmware | flash | flash budget | RAM | RAM budget | stack | stack budget |',
        '| --- | --- | --- | --- | --- | --- | --- |',
    ]
    for name in sorted(measurements):
        sizes = measurements[name]
        limits = budgets.get('firmware', {}).get(name, {})
        if name in stacks and isinstance(stacks[name], dict):
            stack = str(stacks[name].get('total', 'n/a'))
        else:
            stack = 'n/a'
        rows.append(
            '| '
            + ' | '.join(
                [
                    name,
                    str(sizes.get('flash', 'n/a')),
                    str(limits.get('flash', 'n/a')),
                    str(sizes.get('ram', 'n/a')),
                    str(limits.get('ram', 'n/a')),
                    stack,
                    str(limits.get('stack', 'n/a')),
                ]
            )
            + ' |'
        )
    return '\n'.join(rows) + '\n'


def render_page(measurements: dict, stacks: dict, budgets: dict) -> str:
    """The full docs/budgets.md: notice, method, table, trade-offs."""
    return (
        '# Size and stack budgets\n'
        '\n'
        f'{GENERATED_NOTE}\n'
        '\n'
        'Flash, RAM and worst-case static stack per example and per board,\n'
        'measured by the same tools that gate every pull request.\n'
        '\n' + METHOD + '\n'
        '## Firmware\n'
        '\n' + render_table(measurements, stacks, budgets) + '\n'
        'Rows with `n/a` budgets name firmware the budgets file does not\n'
        'constrain yet; the gate reports such rows and never judges them.\n'
        '\n' + TRADE_OFFS
    )


def main(argv: list | None = None) -> int:
    """Render docs/budgets.md from a measurement run."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--measurements', required=True)
    parser.add_argument('--stack', required=True)
    parser.add_argument('--budgets', required=True)
    parser.add_argument('--out', required=True)
    args = parser.parse_args(argv)
    try:
        measurements = json.loads(Path(args.measurements).read_text(encoding='utf-8'))
        stacks = json.loads(Path(args.stack).read_text(encoding='utf-8'))
        budgets = size_report.load_budgets(Path(args.budgets))
    except (OSError, ValueError, size_report.SizeError) as error:
        print(f'budgets_table: error: {error}', file=sys.stderr)
        return 1
    Path(args.out).write_text(render_page(measurements, stacks, budgets), encoding='utf-8')
    return 0


if __name__ == '__main__':
    sys.exit(main())
