#!/usr/bin/env python3
"""Generate Unity runners: one for a test source file, or one for vector files.

`tests` scans a C file for `void test_*(void)` definitions and writes a main
that runs each of them. `vectors` turns every case of the given YAML files
into a test that passes a record of the case to the kind's check function,
`r2s_vec_check_<kind>()` from core/tests/support/vectors.h. Which check runs is
decided at link time, so the same generated file serves the runner self-test
and the real conformance tests.

Usage:
  unity_runner.py tests SOURCE.c OUT.c
  unity_runner.py vectors KIND CHECK.c OUT.c FILE.yaml...

Failures are reported against SOURCE.c, or CHECK.c (the file with the check
functions) for vectors, rather than against the generated runner.
"""

import json
import re
import sys
from pathlib import Path

import yaml

TEST_FN = re.compile(r"^void\s+(test_\w+)\s*\(\s*void\s*\)", re.MULTILINE)
COMMENT = re.compile(r"/\*.*?\*/|//[^\n]*", re.DOTALL)
HEX = re.compile(r"^$|^[0-9a-f]{2}( [0-9a-f]{2})*$")
KINDS = ("crc", "rcobs", "varint")
HEADER = "/* Generated by tools/unity_runner.py; do not edit. */\n"


class VectorError(Exception):
    pass


def test_names(source: str) -> list[str]:
    return TEST_FN.findall(COMMENT.sub("", source))


def _main(names: list[str], prelude: str, reported_file: str) -> str:
    # UnityBegin names the file failures are reported in; UNITY_BEGIN would name this runner.
    runs = "".join(f"    RUN_TEST({n});\n" for n in names)
    begin = f"UnityBegin({json.dumps(reported_file)});"
    return f"{prelude}\nint main(void)\n{{\n    {begin}\n{runs}    return UNITY_END();\n}}\n"


def tests_runner(source: str, names: list[str]) -> str:
    protos = "".join(f"void {n}(void);\n" for n in names)
    name = Path(source).name
    return _main(names, f'{HEADER}/* Runner for {name}. */\n#include "unity.h"\n\n{protos}', source)


def _ident(text: str) -> str:
    return re.sub(r"\W", "_", text)


def _bytes(where: str, field: str, hex_text: object) -> bytes:
    if not isinstance(hex_text, str) or not HEX.match(hex_text):
        raise VectorError(f"{where}: {field} is not a hex byte string: {hex_text!r}")
    return bytes.fromhex(hex_text)


def _array(name: str, data: bytes) -> tuple[str, str]:
    """A C definition for the bytes and the expression a record uses for them."""
    if not data:
        return "", "NULL"
    body = ", ".join(f"0x{b:02x}" for b in data)
    return f"static const uint8_t {name}[] = {{{body}}};\n", name


def _blob(prefix: str, field: str, data: bytes) -> tuple[str, str]:
    """Definition, plus the `bytes, length, "hex"` initializer for a field."""
    if len(data) > 0xFFFF:
        raise VectorError(f"{prefix}: {field} is longer than 65535 bytes")
    definition, expr = _array(f"{prefix}_{field}", data)
    return definition, f'{expr}, {len(data)}u, "{data.hex(" ")}"'


def _case(kind: str, where: str, prefix: str, case: dict) -> tuple[str, str]:
    """C definitions for one case and the initializer of its record's own fields."""
    if not isinstance(case, dict):
        raise VectorError(f"{where}: a case must be a mapping")
    if kind == "crc":
        if "text" in case:
            if not isinstance(case["text"], str) or not case["text"].isascii():
                raise VectorError(f"{where}: text must be an ASCII string")
            data = case["text"].encode("ascii")
        else:
            data = _bytes(where, "data", case.get("data"))
        crc = case.get("crc")
        if not isinstance(crc, int) or not 0 <= crc <= 0xFFFF:
            raise VectorError(f"{where}: crc must be an integer from 0 to 65535")
        definition, blob = _blob(prefix, "data", data)
        return definition, f"{blob}, {crc}u"
    if kind == "rcobs":
        d_def, d = _blob(prefix, "decoded", _bytes(where, "decoded", case.get("decoded")))
        e_def, e = _blob(prefix, "encoded", _bytes(where, "encoded", case.get("encoded")))
        return d_def + e_def, f"{d}, {e}"
    value = case.get("value")
    if not isinstance(value, int) or not 0 <= value <= 0xFFFFFFFF:
        raise VectorError(f"{where}: value must be an integer from 0 to 4294967295")
    definition, blob = _blob(prefix, "encoded", _bytes(where, "encoded", case.get("encoded")))
    return definition, f"{value}ul, {blob}"


def vector_runner(kind: str, files: list[Path], check: str = "vectors") -> str:
    if kind not in KINDS:
        raise VectorError(f"unknown vector kind {kind!r}; the runner supports {', '.join(KINDS)}")
    defs, names = [], []
    for path in files:
        doc = yaml.safe_load(path.read_text(encoding="utf-8"))
        if not isinstance(doc, dict) or not isinstance(doc.get("cases"), list):
            raise VectorError(f"{path.name}: expected a mapping with a cases list")
        covers = " ".join(doc.get("covers") or [])
        for i, case in enumerate(doc["cases"]):
            where = f"{path.name} case {i}"
            prefix = f"v_{_ident(path.stem)}_{i}"
            name = f"test_{kind}_{_ident(path.stem)}_{i}"
            if name in names:
                raise VectorError(f"{where}: another file already produces {name}")
            definition, fields = _case(kind, where, prefix, case)
            defs.append(
                f'{definition}static const r2s_vec_{kind}_t {prefix} = {{"{where}", "{covers}", {fields}}};\n'
                f"static void {name}(void)\n{{\n    r2s_vec_check_{kind}(&{prefix});\n}}\n"
            )
            names.append(name)
    sources = ", ".join(p.name for p in files)
    prelude = f'{HEADER}/* {kind} vectors from {sources}. */\n#include "unity.h"\n#include "vectors.h"\n\n'
    return _main(names, prelude + "\n".join(defs), check)


def main(argv: list[str]) -> int:
    try:
        if len(argv) == 3 and argv[0] == "tests":
            source = Path(argv[1])
            names = test_names(source.read_text(encoding="utf-8"))
            if not names:
                print(f"{source}: no test functions (void test_*(void))")
                return 1
            Path(argv[2]).write_text(tests_runner(str(source), names), encoding="utf-8")
            return 0
        if len(argv) >= 4 and argv[0] == "vectors":
            if argv[1] not in KINDS:
                print(f"unknown vector kind {argv[1]!r}; the runner supports {', '.join(KINDS)}")
                return 2
            out = vector_runner(argv[1], [Path(p) for p in argv[4:]], argv[2])
            Path(argv[3]).write_text(out, encoding="utf-8")
            return 0
    except (VectorError, OSError, yaml.YAMLError) as e:
        print(e)
        return 1
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
