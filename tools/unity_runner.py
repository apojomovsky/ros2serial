"""Generate Unity runners: one for a test source file, or one for vector files.

`tests` scans a C file for `void test_*(void)` definitions and writes a main
that runs each of them. `vectors` turns every case of the given YAML files
into a test that passes a record of the case to the kind's check function,
`r2s_vec_check_<kind>()` from core/tests/support/vectors.h. Which check runs is
decided at link time, so the same generated file serves the runner self-test
and the real conformance tests.

Usage:
  unity_runner.py names SOURCE.c                     print the test names, one per line
  unity_runner.py tests SOURCE.c OUT.c
  unity_runner.py vectors KIND CHECK.c OUT.c FILE.yaml...

Failures are reported against SOURCE.c, or CHECK.c (the file with the check
functions) for vectors, rather than against the generated runner.
"""

import json
import os
import re
import struct
import sys
from pathlib import Path

import yaml

# A definition, not a prototype: the body's brace follows the signature.
TEST_FN = re.compile(r'^void\s+(test_\w+)\s*\(\s*void\s*\)\s*\{', re.MULTILINE)
COMMENT = re.compile(r'/\*.*?\*/|//[^\n]*', re.DOTALL)
HEX = re.compile(r'^$|^[0-9a-f]{2}( [0-9a-f]{2})*$')
KINDS = ('crc', 'frames', 'messages', 'rcobs', 'session', 'time', 'varint')
SPEC_ID = re.compile(r'^[A-Z]{2,4}-\d+$')
HEADER = '/* Generated by tools/unity_runner.py; do not edit. */\n'


class VectorError(Exception):
    pass


def test_names(source: str) -> list[str]:
    names = TEST_FN.findall(COMMENT.sub('', source))
    for n in names:
        if names.count(n) > 1:
            raise VectorError(f'{n} is defined twice')
    return names


def _c_string(text: str) -> str:
    return json.dumps(text)


# With a test name as its argument, a runner runs only that test, so CMake can
# register every test function as its own ctest entry: each then runs alone, in
# a fresh process, in the order ctest --schedule-random picks.
RUN_ONE = """
static int r2s_matched;

static void r2s_run_test(UnityTestFunction fn, const char *name, int argc, char **argv)
{
    if (argc < 2 || strcmp(argv[1], name) == 0) {
        r2s_matched = 1;
        UnityDefaultTestRun(fn, name, __LINE__);
    }
}
"""


def _main(names: list[str], prelude: str, reported_file: str) -> str:
    # UnityBegin names the file failures are reported in; UNITY_BEGIN would name this runner.
    runs = ''.join(f'    r2s_run_test({n}, "{n}", argc, argv);\n' for n in names)
    begin = f'UnityBegin({json.dumps(reported_file)});'
    unknown = '        fprintf(stderr, "no test named %s\\n", argv[1]);\n        return 1;\n'
    return (
        f'{prelude}\n#include <stdio.h>\n#include <string.h>\n{RUN_ONE}\n'
        f'int main(int argc, char **argv)\n{{\n    {begin}\n{runs}'
        f'    if (argc >= 2 && !r2s_matched) {{\n{unknown}    }}\n    return UNITY_END();\n}}\n'
    )


def tests_runner(source: str, names: list[str]) -> str:
    protos = ''.join(f'void {n}(void);\n' for n in names)
    name = Path(source).name
    return _main(
        names, f'{HEADER}/* Runner for {name}. */\n#include "unity.h"\n\n{protos}', source
    )


def _ident(text: str) -> str:
    return re.sub(r'\W', '_', text)


def _bytes(where: str, field: str, hex_text: object) -> bytes:
    if not isinstance(hex_text, str) or not HEX.fullmatch(hex_text):
        raise VectorError(f'{where}: {field} is not a hex byte string: {hex_text!r}')
    return bytes.fromhex(hex_text)


def _array(name: str, data: bytes) -> tuple[str, str]:
    """A C definition for the bytes and the expression a record uses for them."""
    if not data:
        return '', 'NULL'
    body = ', '.join(f'0x{b:02x}' for b in data)
    return f'static const uint8_t {name}[] = {{{body}}};\n', name


def _blob(prefix: str, field: str, data: bytes, text: str | None) -> tuple[str, str]:
    """Definition, plus the `bytes, length, "text"` initializer for a field.

    The text is the vector's own string, not one rebuilt from the bytes, so the
    self-test compares two independent transcriptions."""
    if len(data) > 0xFFFE:
        raise VectorError(f'{prefix}: {field} is longer than 65534 bytes')
    definition, expr = _array(f'{prefix}_{field}', data)
    return definition, f'{expr}, {len(data)}u, {"NULL" if text is None else _c_string(text)}'


def _hex_field(where: str, prefix: str, field: str, case: dict) -> tuple[str, str]:
    data = _bytes(where, field, case.get(field))
    return _blob(prefix, field, data, case[field])


KNOWN_MESSAGE_TYPES = (
    'std_msgs/msg/Float32',
    'geometry_msgs/msg/Twist',
    'sensor_msgs/msg/Range',
    'sensor_msgs/msg/Imu',
    'sensor_msgs/msg/JointState',
    'geometry_msgs/msg/TransformStamped',
    'tf2_msgs/msg/TFMessage',
)

# The struct sizes of the test build the images below must match, padding
# included: LP64 with 8-byte doubles, or m32 where doubles align to 4. The C
# tables read their offsets from the structs, so they follow both; the images
# here name each ABI's layout outright. R2S_VECTOR_ABI selects it, defaulting
# to the 64-bit host; the core CMake sets it from its own -m32 flag.
_VECTOR_ABI = os.environ.get('R2S_VECTOR_ABI', 'lp64')

if _VECTOR_ABI == 'lp64':
    RANGE_STRUCT_SIZE = 60
    IMU_STRUCT_SIZE = 336
    JOINT_STATE_STRUCT_SIZE = 216
    TRANSFORM_STAMPED_STRUCT_SIZE = 120
    TF_MESSAGE_STRUCT_SIZE = 488
    IMU_ORIENTATION = 40
    IMU_ORI_COV = 72
    IMU_ANG_VEL = 144
    IMU_ANG_COV = 168
    IMU_LIN_ACC = 240
    IMU_LIN_COV = 264
    JOINT_STATE_NAME = 36
    JOINT_STATE_NAME_N = 88
    JOINT_STATE_POSITION = 96
    JOINT_STATE_POSITION_N = 128
    JOINT_STATE_VELOCITY = 136
    JOINT_STATE_VELOCITY_N = 168
    JOINT_STATE_EFFORT = 176
    JOINT_STATE_EFFORT_N = 208
elif _VECTOR_ABI == 'm32':
    RANGE_STRUCT_SIZE = 60
    IMU_STRUCT_SIZE = 332
    JOINT_STATE_STRUCT_SIZE = 200
    TRANSFORM_STAMPED_STRUCT_SIZE = 120
    TF_MESSAGE_STRUCT_SIZE = 484
    IMU_ORIENTATION = 36
    IMU_ORI_COV = 68
    IMU_ANG_VEL = 140
    IMU_ANG_COV = 164
    IMU_LIN_ACC = 236
    IMU_LIN_COV = 260
    JOINT_STATE_NAME = 36
    JOINT_STATE_NAME_N = 88
    JOINT_STATE_POSITION = 92
    JOINT_STATE_POSITION_N = 124
    JOINT_STATE_VELOCITY = 128
    JOINT_STATE_VELOCITY_N = 160
    JOINT_STATE_EFFORT = 164
    JOINT_STATE_EFFORT_N = 196
else:
    raise VectorError(f'R2S_VECTOR_ABI is {_VECTOR_ABI!r}, not lp64 or m32')

# The byte order the message struct images pack multi-byte values in. The
# wire stays little-endian while a struct holds its values in the target's
# own order, so the images name native bytes on a big-endian target
# ([DSC-34]). R2S_VECTOR_ORDER selects it, defaulting to little-endian; the
# core CMake sets it from its target.
_VECTOR_ORDER = os.environ.get('R2S_VECTOR_ORDER', 'little')
if _VECTOR_ORDER not in ('little', 'big'):
    raise VectorError(f'R2S_VECTOR_ORDER is {_VECTOR_ORDER!r}, not little or big')
_STRUCT_PREFIX = '<' if _VECTOR_ORDER == 'little' else '>'

# The bounds the handwritten tables give the new types: a vector that exceeds
# them is a bug in the vector, since the tables cannot decode it.
FRAME_ID_BOUND = 24
NAME_COUNT_BOUND = 4
NAME_STRING_BOUND = 12
ARRAY_BOUND = 4

# The tf closure lays out the same on both ABIs: the header ends at 36, the
# child frame id runs 36 to 60, and the transform follows at 64 with its
# rotation 24 past it. Only the TFMessage tail padding differs, which the
# per-ABI sizes above carry.
STAMPED_CHILD = 36
STAMPED_TRANSFORM = 64
TRANSFORM_ROTATION = 24
STAMPED_STRIDE = 120
TF_TRANSFORMS_N = 480
CHILD_FRAME_ID_BOUND = 24
TRANSFORMS_COUNT_BOUND = 4


def _pack_int(where: str, value: object, width: int, signed: bool) -> bytes:
    if isinstance(value, bool) or not isinstance(value, int):
        raise VectorError(f'{where}: expected an integer, not {value!r}')
    try:
        return int(value).to_bytes(width, _VECTOR_ORDER, signed=signed)
    except OverflowError:
        raise VectorError(f'{where}: {value!r} does not fit {width} bytes') from None


def _put_int(
    image: bytearray, offset: int, where: str, value: object, width: int, signed: bool
) -> None:
    image[offset : offset + width] = _pack_int(where, value, width, signed)


def _narrow_bytes(where: str, value: object) -> bytes:
    """The little-endian binary32 of a value on a narrow topic ([ENC-11]):
    a finite value too large for binary32 becomes an infinity of the same
    sign. These are wire bytes, so they stay little-endian on every target."""
    if isinstance(value, dict):
        return _float_bytes(where, value, 4)
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise VectorError(f'{where}: expected a number or {{bits: ...}}, not {value!r}')
    number = float(value)
    try:
        return struct.pack('<f', number)
    except OverflowError:
        return struct.pack('<f', float('inf') if number > 0 else float('-inf'))


def _put_float(
    image: bytearray, offset: int, where: str, value: object, width: int, narrow_decode: bool
) -> None:
    if width == 8 and narrow_decode:
        narrow = _narrow_bytes(where, value)
        image[offset : offset + 8] = struct.pack(
            f'{_STRUCT_PREFIX}d', struct.unpack('<f', narrow)[0]
        )
    else:
        image[offset : offset + width] = _float_bytes(where, value, width)


def _put_string(image: bytearray, offset: int, where: str, value: object, bound: int) -> None:
    if not isinstance(value, str):
        raise VectorError(f'{where}: expected a string, not {value!r}')
    try:
        raw = value.encode('ascii')
    except UnicodeEncodeError:
        raise VectorError(f'{where}: {value!r} is not ASCII') from None
    if len(raw) > bound:
        raise VectorError(f'{where}: {value!r} exceeds the bound of {bound}')
    image[offset : offset + len(raw)] = raw
    image[offset + len(raw)] = 0


def _put_time(image: bytearray, offset: int, where: str, message: dict) -> None:
    stamp = message['stamp']
    _put_int(image, offset, f'{where}.sec', stamp['sec'], 4, True)
    _put_int(image, offset + 4, f'{where}.nanosec', stamp['nanosec'], 4, False)


def _put_header(image: bytearray, offset: int, where: str, message: dict) -> None:
    _put_time(image, offset, f'{where}.stamp', message)
    _put_string(image, offset + 8, f'{where}.frame_id', message['frame_id'], FRAME_ID_BOUND)


def _put_vector3(
    image: bytearray, offset: int, where: str, message: dict, narrow_decode: bool
) -> None:
    for i, axis in enumerate(('x', 'y', 'z')):
        _put_float(image, offset + 8 * i, f'{where}.{axis}', message[axis], 8, narrow_decode)


def _put_quaternion(
    image: bytearray, offset: int, where: str, message: dict, narrow_decode: bool
) -> None:
    for i, axis in enumerate(('x', 'y', 'z', 'w')):
        _put_float(image, offset + 8 * i, f'{where}.{axis}', message[axis], 8, narrow_decode)


def _put_float64_array(
    image: bytearray,
    offset: int,
    where: str,
    values: object,
    bound: int,
    narrow_decode: bool,
) -> None:
    if not isinstance(values, list):
        raise VectorError(f'{where}: expected a list, not {values!r}')
    if len(values) > bound:
        raise VectorError(f'{where}: {len(values)} elements exceed the bound of {bound}')
    for i, value in enumerate(values):
        _put_float(image, offset + 8 * i, f'{where}[{i}]', value, 8, narrow_decode)


def _put_string_array(
    image: bytearray,
    offset: int,
    count_offset: int,
    where: str,
    values: object,
    bound: int,
    string_bound: int,
) -> None:
    if not isinstance(values, list):
        raise VectorError(f'{where}: expected a list, not {values!r}')
    if len(values) > bound:
        raise VectorError(f'{where}: {len(values)} elements exceed the bound of {bound}')
    for i, value in enumerate(values):
        _put_string(image, offset + (string_bound + 1) * i, f'{where}[{i}]', value, string_bound)
    _put_int(image, count_offset, where, len(values), 1, False)


def _put_float64_sequence(
    image: bytearray,
    offset: int,
    count_offset: int,
    where: str,
    values: object,
    bound: int,
    narrow_decode: bool,
) -> None:
    _put_float64_array(image, offset, where, values, bound, narrow_decode)
    _put_int(image, count_offset, where, len(values), 1, False)


def _struct_range(where: str, message: dict, image: bytearray, narrow_decode: bool) -> None:
    _put_header(image, 0, f'{where}.header', message['header'])
    _put_int(image, 36, f'{where}.radiation_type', message['radiation_type'], 1, False)
    for i, field in enumerate(('field_of_view', 'min_range', 'max_range', 'range', 'variance')):
        _put_float(image, 40 + 4 * i, f'{where}.{field}', message[field], 4, False)


def _struct_imu(where: str, message: dict, image: bytearray, narrow_decode: bool) -> None:
    _put_header(image, 0, f'{where}.header', message['header'])
    _put_quaternion(
        image, IMU_ORIENTATION, f'{where}.orientation', message['orientation'], narrow_decode
    )
    _put_float64_array(
        image,
        IMU_ORI_COV,
        f'{where}.orientation_covariance',
        message['orientation_covariance'],
        9,
        narrow_decode,
    )
    _put_vector3(
        image, IMU_ANG_VEL, f'{where}.angular_velocity', message['angular_velocity'], narrow_decode
    )
    _put_float64_array(
        image,
        IMU_ANG_COV,
        f'{where}.angular_velocity_covariance',
        message['angular_velocity_covariance'],
        9,
        narrow_decode,
    )
    _put_vector3(
        image,
        IMU_LIN_ACC,
        f'{where}.linear_acceleration',
        message['linear_acceleration'],
        narrow_decode,
    )
    _put_float64_array(
        image,
        IMU_LIN_COV,
        f'{where}.linear_acceleration_covariance',
        message['linear_acceleration_covariance'],
        9,
        narrow_decode,
    )


def _put_transform(
    image: bytearray, offset: int, where: str, message: dict, narrow_decode: bool
) -> None:
    _put_vector3(image, offset, f'{where}.translation', message['translation'], narrow_decode)
    _put_quaternion(
        image, offset + TRANSFORM_ROTATION, f'{where}.rotation', message['rotation'], narrow_decode
    )


def _put_transform_stamped(
    image: bytearray, offset: int, where: str, message: dict, narrow_decode: bool
) -> None:
    _put_header(image, offset, f'{where}.header', message['header'])
    _put_string(
        image,
        offset + STAMPED_CHILD,
        f'{where}.child_frame_id',
        message['child_frame_id'],
        CHILD_FRAME_ID_BOUND,
    )
    _put_transform(
        image,
        offset + STAMPED_TRANSFORM,
        f'{where}.transform',
        message['transform'],
        narrow_decode,
    )


def _struct_tf_message(where: str, message: dict, image: bytearray, narrow_decode: bool) -> None:
    transforms = message['transforms']
    if not isinstance(transforms, list):
        raise VectorError(f'{where}: transforms is a list, not {transforms!r}')
    if len(transforms) > TRANSFORMS_COUNT_BOUND:
        raise VectorError(
            f'{where}: {len(transforms)} transforms exceed the bound of {TRANSFORMS_COUNT_BOUND}'
        )
    for index, stamped in enumerate(transforms):
        _put_transform_stamped(
            image, index * STAMPED_STRIDE, f'{where}.transforms[{index}]', stamped, narrow_decode
        )
    _put_int(image, TF_TRANSFORMS_N, where, len(transforms), 1, False)


def _struct_joint_state(where: str, message: dict, image: bytearray, narrow_decode: bool) -> None:
    _put_header(image, 0, f'{where}.header', message['header'])
    _put_string_array(
        image,
        JOINT_STATE_NAME,
        JOINT_STATE_NAME_N,
        f'{where}.name',
        message['name'],
        NAME_COUNT_BOUND,
        NAME_STRING_BOUND,
    )
    _put_float64_sequence(
        image,
        JOINT_STATE_POSITION,
        JOINT_STATE_POSITION_N,
        f'{where}.position',
        message['position'],
        ARRAY_BOUND,
        narrow_decode,
    )
    _put_float64_sequence(
        image,
        JOINT_STATE_VELOCITY,
        JOINT_STATE_VELOCITY_N,
        f'{where}.velocity',
        message['velocity'],
        ARRAY_BOUND,
        narrow_decode,
    )
    _put_float64_sequence(
        image,
        JOINT_STATE_EFFORT,
        JOINT_STATE_EFFORT_N,
        f'{where}.effort',
        message['effort'],
        ARRAY_BOUND,
        narrow_decode,
    )


def _struct_image(
    where: str, type_name: str, message: dict, narrow_decode: bool, fill: int
) -> bytes:
    """The C struct image of a message: zeros fill padding on encode, while a
    decode image keeps the 0xA5 the check prefills wherever the interpreter
    writes nothing."""
    if type_name == 'sensor_msgs/msg/Range':
        image = bytearray([fill]) * RANGE_STRUCT_SIZE
        _struct_range(where, message, image, narrow_decode)
    elif type_name == 'sensor_msgs/msg/Imu':
        image = bytearray([fill]) * IMU_STRUCT_SIZE
        _struct_imu(where, message, image, narrow_decode)
    elif type_name == 'sensor_msgs/msg/JointState':
        image = bytearray([fill]) * JOINT_STATE_STRUCT_SIZE
        _struct_joint_state(where, message, image, narrow_decode)
    elif type_name == 'geometry_msgs/msg/TransformStamped':
        image = bytearray([fill]) * TRANSFORM_STAMPED_STRUCT_SIZE
        _put_transform_stamped(image, 0, where, message, narrow_decode)
    elif type_name == 'tf2_msgs/msg/TFMessage':
        image = bytearray([fill]) * TF_MESSAGE_STRUCT_SIZE
        _struct_tf_message(where, message, image, narrow_decode)
    else:
        raise VectorError(f'{where}: no struct layout for {type_name}')
    return bytes(image)


def _float_bytes(where: str, value: object, width: int) -> bytes:
    """The struct bytes of a message float: a number or `{bits: ...}`."""
    prefix = _STRUCT_PREFIX
    if isinstance(value, dict):
        bits = value.get('bits')
        if (
            not isinstance(bits, str)
            or len(bits) != 2 * width
            or any(digit not in '0123456789abcdefABCDEF' for digit in bits)
        ):
            raise VectorError(
                f'{where}: bits are {2 * width} hex digits of a binary{8 * width} pattern'
            )
        raw = bytes.fromhex(bits)
        return raw[::-1] if _VECTOR_ORDER == 'little' else raw
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise VectorError(f'{where}: expected a number or {{bits: ...}}, not {value!r}')
    number = float(value)
    try:
        packed = struct.pack(f'{prefix}f' if width == 4 else f'{prefix}d', number)
    except OverflowError:
        raise VectorError(f'{where}: {value!r} does not fit binary{8 * width}') from None
    if width == 4 and struct.unpack(f'{prefix}f', packed)[0] != number:
        raise VectorError(f'{where}: {value!r} is not exactly representable in binary32')
    return packed


def _messages_case(where: str, prefix: str, case: dict) -> tuple[str, str]:
    """A message vector's record: its type, narrow flag, payload and struct bytes.

    The struct bytes come in two blobs: `encode` holds the message the vector
    states, and `decode` holds what the payload decodes to. They differ only on
    a narrow topic, where the payload's binary32 widens to the binary64 beside
    it. A type the C core does not know is a runner error, not a silent skip.
    """
    for required in ('type', 'profile', 'message', 'payload'):
        if required not in case:
            raise VectorError(f'{where}: a message vector needs {required}')
    type_name = case['type']
    if type_name not in KNOWN_MESSAGE_TYPES:
        raise VectorError(f'{where}: the C runner knows {KNOWN_MESSAGE_TYPES}, not {type_name}')
    profile = case['profile']
    if not isinstance(profile, dict) or not isinstance(profile.get('narrow_float64', False), bool):
        raise VectorError(f'{where}: profile.narrow_float64 is a bool')
    narrow = profile.get('narrow_float64', False)
    payload = _bytes(where, 'payload', case.get('payload'))
    try:
        message = case['message']
        if type_name == 'std_msgs/msg/Float32':
            if len(payload) != 4:
                raise VectorError(f'{where}: a Float32 payload is 4 bytes')
            blobs = [_float_bytes(f'{where}.data', message['data'], 4)]
            encode = decode = b''.join(blobs)
        elif type_name == 'geometry_msgs/msg/Twist':
            parts = [
                _float_bytes(f'{where}.{group}.{axis}', message[group][axis], 8)
                for group in ('linear', 'angular')
                for axis in ('x', 'y', 'z')
            ]
            encode = b''.join(parts)
            if narrow:
                if len(payload) != 24:
                    raise VectorError(f'{where}: a narrow Twist payload is 24 bytes')
                decode = b''.join(
                    struct.pack(
                        f'{_STRUCT_PREFIX}d', struct.unpack('<f', payload[i * 4 : (i + 1) * 4])[0]
                    )
                    for i in range(6)
                )
            else:
                if len(payload) != 48:
                    raise VectorError(f'{where}: a Twist payload is 48 bytes')
                decode = encode
        else:
            encode = _struct_image(where, type_name, message, False, 0x00)
            decode = _struct_image(where, type_name, message, narrow, 0xA5)
    except (KeyError, TypeError, AttributeError) as caught:
        raise VectorError(
            f'{where}: the message is not a mapping for {type_name}: {caught}'
        ) from caught
    p_def, p = _blob(prefix, 'payload', payload, case['payload'])
    e_def, e_expr = _array(f'{prefix}_encode', encode)
    d_def, d_expr = _array(f'{prefix}_decode', decode)
    e = f'{e_expr}, {len(encode)}u'
    d = f'{d_expr}, {len(decode)}u'
    return p_def + e_def + d_def, f'{_c_string(type_name)}, {1 if narrow else 0}u, {p}, {e}, {d}'


def _case(kind: str, where: str, prefix: str, case: dict) -> tuple[str, str]:
    """C definitions for one case and the initializer of its record's own fields."""
    if not isinstance(case, dict):
        raise VectorError(f'{where}: a case must be a mapping')
    if kind == 'crc':
        crc = case.get('crc')
        if not isinstance(crc, int) or not 0 <= crc <= 0xFFFF:
            raise VectorError(f'{where}: crc must be an integer from 0 to 65535')
        if 'text' in case:
            text = case['text']
            if not isinstance(text, str) or not text.isascii():
                raise VectorError(f'{where}: text must be an ASCII string')
            definition, blob = _blob(prefix, 'data', text.encode('ascii'), None)
            return definition, f'{blob}, {_c_string(text)}, {crc}u'
        definition, blob = _hex_field(where, prefix, 'data', case)
        return definition, f'{blob}, NULL, {crc}u'
    if kind == 'messages':
        # A message vector is one file for one message: its own fields are the case.
        return _messages_case(where, prefix, case)
    # A reject case has no decoded side; its record carries the rule's ID instead of NULL.
    if kind == 'frames':
        topic_id, seq = case.get('topic_id'), case.get('seq')
        for field, value in (('topic_id', topic_id), ('seq', seq)):
            if not isinstance(value, int) or not 0 <= value <= 0xFF:
                raise VectorError(f'{where}: {field} must be an integer from 0 to 255')
        p_def, p = _hex_field(where, prefix, 'payload', case)
        f_def, f = _hex_field(where, prefix, 'frame', case)
        w_def, w = _hex_field(where, prefix, 'wire', case)
        return p_def + f_def + w_def, f'{topic_id}u, {seq}u, {p}, {f}, {w}'
    reject = case.get('reject')
    if reject is not None and not (isinstance(reject, str) and SPEC_ID.fullmatch(reject)):
        raise VectorError(f'{where}: reject must be a spec ID such as COB-5')
    rule = 'NULL' if reject is None else _c_string(reject)
    e_def, e = _hex_field(where, prefix, 'encoded', case)
    if kind == 'rcobs':
        if reject is not None:
            d_def, d = _blob(prefix, 'decoded', b'', '')
        else:
            d_def, d = _hex_field(where, prefix, 'decoded', case)
        return d_def + e_def, f'{d}, {e}, {rule}'
    value = 0 if reject is not None else case.get('value')
    if not isinstance(value, int) or not 0 <= value <= 0xFFFFFFFF:
        raise VectorError(f'{where}: value must be an integer from 0 to 4294967295')
    return e_def, f'{value}ul, {e}, {rule}'


def _session_case(where: str, prefix: str, doc: dict) -> tuple[str, str]:
    """A transcript vector's record: its name and its ordered steps.

    A step names its side, its time in milliseconds and its wire bytes with
    the delimiter. The C check replays the steps through the MCU session.
    """
    name = doc.get('name')
    if not isinstance(name, str) or not name:
        raise VectorError(f'{where}: a session vector needs a name')
    steps = doc.get('steps')
    if not isinstance(steps, list) or not steps:
        raise VectorError(f'{where}: a session vector needs a steps list')
    defs = ''
    inits = []
    for i, step in enumerate(steps):
        at = f'{where} step {i}'
        if not isinstance(step, dict):
            raise VectorError(f'{at}: a step must be a mapping')
        side = step.get('from')
        if side not in ('host', 'mcu'):
            raise VectorError(f'{at}: from must be host or mcu, not {side!r}')
        at_ms = step.get('at_ms', 0)
        if not isinstance(at_ms, int) or isinstance(at_ms, bool) or at_ms < 0:
            raise VectorError(f'{at}: at_ms must be a non-negative integer')
        data = _bytes(at, 'frame', step.get('frame'))
        definition, blob = _blob(f'{prefix}_s{i}', 'frame', data, step['frame'])
        defs += definition
        host = '1u' if side == 'host' else '0u'
        inits.append(f'{{{host}, {at_ms}u, {blob}}}')
    defs += f'static const r2s_vec_session_step_t {prefix}_steps[] = {{{", ".join(inits)}}};\n'
    fields = f'{_c_string(name)}, {prefix}_steps, {len(steps)}u'
    return defs, fields


def _time_case(where: str, prefix: str, doc: dict, case: dict) -> tuple[str, str]:
    """A time vector case's record: the tick rate, the correction, the tick and the time it makes.

    The integers keep their own widths, so a wraparound or a negative drift is
    transcribed exactly; the C check compares them with the core's arithmetic.
    """
    if not isinstance(case, dict):
        raise VectorError(f'{where}: a case must be a mapping')
    tick_hz = doc.get('tick_hz')
    if (
        not isinstance(tick_hz, int)
        or isinstance(tick_hz, bool)
        or not 1000 <= tick_hz <= 0xFFFFFFFF
    ):
        raise VectorError(f'{where}: tick_hz must be an integer from 1000 to 4294967295')
    for field, low, high in (
        ('tick0', 0, 0xFFFFFFFF),
        ('nanosec0', 0, 999999999),
        ('tick', 0, 0xFFFFFFFF),
    ):
        value = case.get(field)
        if not isinstance(value, int) or isinstance(value, bool) or not low <= value <= high:
            raise VectorError(f'{where}: {field} must be an integer from {low} to {high}')
    sec0 = case.get('sec0')
    if (
        not isinstance(sec0, int)
        or isinstance(sec0, bool)
        or not -0x80000000 <= sec0 <= 0x7FFFFFFF
    ):
        raise VectorError(f'{where}: sec0 must be an integer from -2147483648 to 2147483647')
    drift = case.get('drift_ppm')
    if not isinstance(drift, int) or isinstance(drift, bool) or not -20000 <= drift <= 20000:
        raise VectorError(f'{where}: drift_ppm must be an integer from -20000 to 20000')
    expect = case.get('expect')
    if expect == 'unsynced':
        synced, sec, nanosec = 0, 0, 0
    elif isinstance(expect, dict):
        sec, nanosec = expect.get('sec'), expect.get('nanosec')
        if (
            not isinstance(sec, int)
            or isinstance(sec, bool)
            or not -0x80000000 <= sec <= 0x7FFFFFFF
        ):
            raise VectorError(
                f'{where}: expect.sec must be an integer from -2147483648 to 2147483647'
            )
        if (
            not isinstance(nanosec, int)
            or isinstance(nanosec, bool)
            or not 0 <= nanosec <= 999999999
        ):
            raise VectorError(f'{where}: expect.nanosec must be an integer from 0 to 999999999')
        synced = 1
    else:
        raise VectorError(f"{where}: expect is 'unsynced' or a sec/nanosec mapping")
    tick0, nanosec0, tick = case['tick0'], case['nanosec0'], case['tick']
    fields = (
        f'{tick_hz}u, {tick0}u, (int32_t){sec0}, {nanosec0}u, (int16_t){drift}, {tick}u, '
        f'{synced}u, (int32_t){sec}, {nanosec}u'
    )
    return '', fields


def vector_runner(kind: str, files: list[Path], check: str = 'vectors') -> str:
    if kind not in KINDS:
        raise VectorError(f'unknown vector kind {kind!r}; the runner supports {", ".join(KINDS)}')
    defs, names = [], []
    for path in files:
        doc = yaml.safe_load(path.read_text(encoding='utf-8'))
        if not isinstance(doc, dict):
            raise VectorError(f'{path}: expected a mapping')
        if kind in ('frames', 'messages', 'session'):
            cases = [doc]
        elif isinstance(doc.get('cases'), list):
            cases = doc['cases']
        else:
            raise VectorError(f'{path}: expected a mapping with a cases list')
        covers = ' '.join(doc.get('covers') or [])
        for i, case in enumerate(cases):
            one_file = kind in ('frames', 'messages', 'session')
            where = str(path) if one_file else f'{path} case {i}'
            prefix = f'v_{_ident(path.stem)}' if one_file else f'v_{_ident(path.stem)}_{i}'
            name = (
                f'test_{kind}_{_ident(path.stem)}'
                if one_file
                else f'test_{kind}_{_ident(path.stem)}_{i}'
            )
            if name in names:
                raise VectorError(f'{where}: another file already produces {name}')
            if kind == 'session':
                definition, fields = _session_case(where, prefix, case)
            elif kind == 'time':
                definition, fields = _time_case(where, prefix, doc, case)
            else:
                definition, fields = _case(kind, where, prefix, case)
            defs.append(
                f'{definition}static const r2s_vec_{kind}_t {prefix} = '
                f'{{{_c_string(where)}, {_c_string(covers)}, {fields}}};\n'
                f'static void {name}(void)\n{{\n    r2s_vec_check_{kind}(&{prefix});\n}}\n'
            )
            names.append(name)
    sources = ', '.join(p.name for p in files)
    prelude = (
        f'{HEADER}/* {kind} vectors from {sources}. */\n#include "unity.h"\n'
        '#include "vectors.h"\n\n'
    )
    return _main(names, prelude + '\n'.join(defs), check)


def main(argv: list[str]) -> int:
    try:
        if len(argv) == 2 and argv[0] == 'names':
            print('\n'.join(test_names(Path(argv[1]).read_text(encoding='utf-8'))))
            return 0
        if len(argv) == 3 and argv[0] == 'tests':
            source = Path(argv[1])
            try:
                names = test_names(source.read_text(encoding='utf-8'))
            except VectorError as e:
                print(f'{source}: {e}')
                return 1
            if not names:
                print(f'{source}: no test functions (void test_*(void))')
                return 1
            Path(argv[2]).write_text(tests_runner(str(source), names), encoding='utf-8')
            return 0
        if len(argv) >= 4 and argv[0] == 'vectors':
            if argv[1] not in KINDS:
                print(f'unknown vector kind {argv[1]!r}; the runner supports {", ".join(KINDS)}')
                return 2
            out = vector_runner(argv[1], [Path(p) for p in argv[4:]], argv[2])
            Path(argv[3]).write_text(out, encoding='utf-8')
            return 0
    except (VectorError, OSError, yaml.YAMLError) as e:
        print(e)
        return 1
    print(__doc__)
    return 2


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
