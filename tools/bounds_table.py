"""The built-in types' limits table in docs/message-bounds.md.

The page carries one block between two markers, and the block is what
`r2s-gen limits` prints, per distro, with the distros that share a table
named once. The docs job renders the same block and fails when the
checked-in copy differs, so editing `BUNDLE_BOUNDS` without refreshing the
page breaks the gate instead of leaving numbers nobody chose unstated.
"""

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / 'gen'))

from r2s_gen import bundle  # noqa: E402
from r2s_gen import limits  # noqa: E402

PAGE = Path('docs') / 'message-bounds.md'
BEGIN = '<!-- bounds-table: begin -->'
END = '<!-- bounds-table: end -->'
NOTE = (
    '<!-- generated by tools/bounds_table.py from `r2s-gen limits`;'
    ' refresh with make bounds-table -->'
)
COMMENT = '# bundled types, distro '


def _table(distro: str) -> str:
    """One distro's table without its own distro line, which the heading replaces."""
    text = limits.table(distro)
    return text.split('\n', 1)[1]


def render_block() -> str:
    """Render the marked block, one table per group of distros that share it."""
    groups: list[tuple[list[str], str]] = []
    for distro in bundle.DISTROS:
        body = _table(distro)
        for distros, other in groups:
            if other == body:
                distros.append(distro)
                break
        else:
            groups.append(([distro], body))
    parts = [BEGIN, NOTE, '']
    for distros, body in groups:
        listed = [f'`{distro}`' for distro in distros]
        names = listed[0] if len(listed) == 1 else f'{", ".join(listed[:-1])} and {listed[-1]}'
        parts += [f'{names}:', '', '```text', body.rstrip('\n'), '```', '']
    parts.append(END)
    return '\n'.join(parts)


def check(text: str) -> list[str]:
    """Every way the page's block differs from the command; empty when current."""
    start = text.find(BEGIN)
    end = text.find(END)
    if start < 0:
        return [f'{PAGE}: no {BEGIN} marker; add the block make bounds-table writes']
    if end < start:
        return [f'{PAGE}: no {END} marker after {BEGIN}; add the block make bounds-table writes']
    found = text[start : end + len(END)]
    if found == render_block():
        return []
    return [
        f'{PAGE}: the limits table differs from `r2s-gen limits`;'
        ' run make bounds-table and commit it'
    ]


def with_block(text: str, block: str) -> str:
    """The page with its marked block replaced, the prose on either side kept."""
    start = text.find(BEGIN)
    end = text.find(END)
    if start < 0 or end < start:
        raise ValueError(f'{PAGE} carries no marked block to replace')
    rest = text[end + len(END) :]
    # The block carries no trailing newline of its own, so the page's one
    # separator survives a refresh instead of growing by a line each run.
    return text[:start] + block + rest


def main(argv: list[str] | None = None) -> int:
    """Check the page, or rewrite its block with --write; exit 1 on drift."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail on a stale block (default)')
    parser.add_argument('--write', action='store_true', help='rewrite the block in place')
    args = parser.parse_args(argv)
    path = ROOT / PAGE
    text = path.read_text(encoding='utf-8')
    if args.write:
        path.write_text(with_block(text, render_block()), encoding='utf-8')
        print(f'bounds-table: refreshed {PAGE}')
        return 0
    problems = check(text)
    for problem in problems:
        print(problem)
    return 1 if problems else 0


if __name__ == '__main__':
    sys.exit(main())
