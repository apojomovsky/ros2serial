"""Map a changed-file list to the ci-test.sh scopes that read those files.

Each rule names where a ci-test.sh section reads: the script it calls and
the tree that script builds. Suite machinery and unknown paths map to FULL,
so an unknown path runs everything instead of too little.
"""

import argparse
import os
import subprocess
import sys

CHEAP = {"LINT": "1", "COMMITS": "1"}

FULL = {"FULL": "1"}

DOC_NAMES = ("README.md", "CONTRIBUTING.md", "AGENTS.md")

