def scopes_for_paths(paths):
    found = dict(CHEAP)
    for path in paths:
        if not path:
            continue
        scopes = _scopes_for_path(path.strip())
        if scopes is FULL:
            return dict(FULL)
        for scope, value in scopes.items():
            if scope == "E2E" and found.get("E2E") not in (None, value):
                found["E2E"] = "both"
            else:
                found[scope] = value
    return found


def _scopes_for_path(path):
    for prefix, scopes in PREFIX_RULES:
        if path == prefix.rstrip("/") or path.startswith(prefix):
            return scopes
    name = path.rsplit("/", 1)[-1]
    if name in DOC_NAMES or name.endswith(".md"):
        return {"DOCS": "1"}
    if path in ("Makefile", "VERSION"):
        return FULL
    return FULL


def _git_lines(*args):
    proc = subprocess.run(["git", *args], capture_output=True, text=True, check=False)
    if proc.returncode != 0:
        raise RuntimeError(f"git {' '.join(args)} failed: {proc.stderr.strip()}")
    return [line for line in proc.stdout.splitlines() if line]


def changed_paths(base):
    """Files changed since the merge base, committed and uncommitted."""
    merge_base = _git_lines("merge-base", base, "HEAD")[0]
    paths = set(_git_lines("diff", "--name-only", merge_base, "HEAD"))
    paths.update(_git_lines("diff", "--name-only", "HEAD"))
    paths.update(_git_lines("ls-files", "--others", "--exclude-standard"))
    return sorted(paths)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--base", default="origin/master")
    args = parser.parse_args(argv)
    if os.environ.get("R2S_FULL") == "1":
        print("FULL=1")
        return 0
    try:
        paths = changed_paths(args.base)
    except (RuntimeError, IndexError) as exc:
        print(f"scopes_for_diff: {exc}; running the full suite", file=sys.stderr)
        print("FULL=1")
        return 0
    result = scopes_for_paths(paths)
    for scope in sorted(result):
        print(f"{scope}={result[scope]}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
