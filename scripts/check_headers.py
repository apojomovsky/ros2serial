#!/usr/bin/env python3
"""Every hand-written source file carries the MIT licence header.

The header is the one ament_copyright accepts for MIT (its mit_header.txt
with the repository's copyright line): the line
Copyright (c) 2026 Alexis Pojomovsky followed by the MIT permission text.
The same header clears cpplint's legal/copyright on the C++ side, so one
standard covers the whole tree instead of a second parallel mechanism.

Scope is the hand-written sources under core, bridge, gen, ports, examples
and tools: C and C++ (//), Python, shell, CMake and sketch files (# for the
latter group, // for C-like and Arduino sources), plus CMakeLists.txt.
Generated files keep their own Generated by r2s-gen notice and are exempt;
the vendored Unity sources under core/tests/vendor keep their own notices.

The scan reads the checkout's tracked files plus untracked files git does
not ignore, so a new source file fails before it is added and ignored test
residue such as gen/cpp_stage never counts. Outside a checkout every file
present counts instead.

Exits 1 with one line per problem.
"""

import subprocess
import sys
from pathlib import Path

SCOPED_DIRS = ('core', 'bridge', 'gen', 'ports', 'examples', 'tools')
SUFFIXES = (
    '.c',
    '.h',
    '.cc',
    '.cpp',
    '.cxx',
    '.hh',
    '.hpp',
    '.hxx',
    '.ino',
    '.py',
    '.sh',
    '.cmake',
    '.mjs',
)
SPECIAL_NAMES = ('CMakeLists.txt',)
VENDOR_PREFIXES = ('core/tests/vendor/',)
HOLDER = 'Copyright (c) 2026 Alexis Pojomovsky'
MIT_MARKER = 'Permission is hereby granted'
GENERATED_MARKER = 'Generated by r2s-gen'


def in_scope(path: Path, root: Path) -> bool:
    """A path counts when it is a hand-written source under a scoped dir."""
    try:
        rel = path.relative_to(root).as_posix()
    except ValueError:
        return False
    if not rel.startswith(SCOPED_DIRS):
        return False
    if rel.startswith(VENDOR_PREFIXES):
        return False
    return path.suffix in SUFFIXES or path.name in SPECIAL_NAMES


def first_block(text: str, style: str) -> str:
    """The leading comment block, past any shebang or encoding lines."""
    lines = text.splitlines()
    i = 0
    while i < len(lines):
        stripped = lines[i].strip()
        if stripped.startswith('#!') or 'coding=' in stripped or 'coding:' in stripped:
            i += 1
        elif not stripped:
            i += 1
        else:
            break
    block = []
    if i < len(lines) and style == 'hash' and lines[i].lstrip().startswith('#'):
        while i < len(lines) and lines[i].lstrip().startswith('#'):
            block.append(lines[i].lstrip()[1:])
            i += 1
    elif i < len(lines) and lines[i].lstrip().startswith('//'):
        while i < len(lines) and lines[i].lstrip().startswith('//'):
            block.append(lines[i].lstrip()[2:])
            i += 1
    elif i < len(lines) and lines[i].lstrip().startswith('/*'):
        while i < len(lines):
            block.append(lines[i])
            if '*/' in lines[i]:
                break
            i += 1
    return '\n'.join(block)


def style_for(path: Path) -> str:
    """Hash comments for scripting sources, slashes for compiled ones."""
    if path.suffix in ('.py', '.sh', '.cmake') or path.name == 'CMakeLists.txt':
        return 'hash'
    return 'slash'


def problems_for(path: Path) -> list[str]:
    """The missing-header complaint for one file, or nothing when it passes."""
    try:
        text = path.read_text(encoding='utf-8')
    except (OSError, UnicodeDecodeError) as exc:
        return [f'{path}: cannot be read: {exc}']
    block = first_block(text, style_for(path))
    if GENERATED_MARKER in block:
        return []
    if HOLDER in block and MIT_MARKER in block:
        return []
    return [f'{path}: missing the MIT licence header']


def candidate_files(root: Path) -> list[Path]:
    """The checkout's tracked files plus untracked files git does not ignore.

    Outside a checkout there is no index, and the files present are the whole
    content, so all of them count and the rule stays meaningful in a tarball
    and in a test's throwaway tree.
    """
    try:
        listing = subprocess.run(
            [
                'git',
                '-C',
                str(root),
                'ls-files',
                '-z',
                '--cached',
                '--others',
                '--exclude-standard',
            ],
            capture_output=True,
            text=True,
            check=True,
        ).stdout
    except (OSError, subprocess.CalledProcessError):
        return sorted(p for p in root.rglob('*') if p.is_file())
    return [root / p for p in listing.split('\0') if p]


def check(root: Path) -> list[str]:
    """Every scoped source file under root, with one line per headerless file."""
    problems = []
    for path in candidate_files(root):
        if path.is_file() and in_scope(path, root):
            problems.extend(problems_for(path))
    return problems


def main() -> int:
    root = Path(__file__).resolve().parent.parent
    problems = check(root)
    for problem in problems:
        print(problem)
    return 1 if problems else 0


if __name__ == '__main__':
    sys.exit(main())
