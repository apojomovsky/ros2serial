"""Every hand-written source file carries the SPDX licence header.

The header is the two-liner AGENTS.md agrees on: the line
SPDX-License-Identifier: MIT followed by the copyright line
Copyright (c) 2026 Alexis Pojomovsky and ros2serial contributors, with `#`
in place of `//` for Python, shell, CMake and YAML sources. The old full MIT
block fails, and so does a file carrying both forms. The same header clears
cpplint's legal/copyright on the C++ side, since that check only looks for
a copyright line.

Scope is every tracked source file in the tree: C and C++ (//), Python,
shell, CMake, YAML and sketch files (# for the latter group, // for C-like
and Arduino sources), plus CMakeLists.txt. The scan reads the checkout's
tracked files plus untracked files git does not ignore, so a new source file
fails before it is added and ignored test residue such as gen/cpp_stage
never counts. Outside a checkout every file present counts instead.

These stay headerless, each with its reason: the vendored Unity sources
keep their upstream notices; the generator snapshots stay byte-identical
to the emitter output the tests pin; the checked-in r2s_generated firmware
pair is emitter output the firmware tests pin; .gitkeep placeholders are
owned by check_layout; and any file the generator banners keeps its own
notice, since the emitter owns those bytes.

Exits 1 with one line per problem.
"""

import subprocess
import sys
from pathlib import Path

SUFFIXES = (
    '.c',
    '.h',
    '.cc',
    '.cpp',
    '.cxx',
    '.hh',
    '.hpp',
    '.hxx',
    '.ino',
    '.py',
    '.sh',
    '.cmake',
    '.mjs',
    '.yaml',
    '.yml',
)
SPECIAL_NAMES = ('CMakeLists.txt',)
EXEMPT_PREFIXES = (
    (
        'core/tests/vendor/',
        'vendored Unity sources keep their upstream notices',
    ),
    (
        'gen/tests/golden/',
        'emitter snapshots stay byte-identical to the generator output',
    ),
)
EXEMPT_NAMES = (
    (
        'r2s_generated.c',
        'checked-in emitter output pinned by the firmware tests',
    ),
    (
        'r2s_generated.h',
        'checked-in emitter output pinned by the firmware tests',
    ),
    ('.gitkeep', 'empty-directory placeholder owned by check_layout'),
)
SPDX_MARKER = 'SPDX-License-Identifier: MIT'
HOLDER = 'Copyright (c) 2026 Alexis Pojomovsky and ros2serial contributors'
OLD_MIT_MARKER = 'Permission is hereby granted'
GENERATED_MARKER = 'Generated by r2s-gen'


def exemption_reason(rel: str, name: str) -> str | None:
    """Why a source path stays headerless, or None when it must carry one."""
    for prefix, reason in EXEMPT_PREFIXES:
        if rel.startswith(prefix):
            return reason
    for exempt_name, reason in EXEMPT_NAMES:
        if name == exempt_name:
            return reason
    return None


def in_scope(path: Path, root: Path) -> bool:
    """A path counts when it is a non-exempt source file anywhere in the tree."""
    try:
        rel = path.relative_to(root).as_posix()
    except ValueError:
        return False
    if path.suffix not in SUFFIXES and path.name not in SPECIAL_NAMES:
        return False
    return exemption_reason(rel, path.name) is None


def first_block(text: str, style: str) -> str:
    """The leading comment block, past any shebang or encoding lines."""
    lines = text.splitlines()
    i = 0
    while i < len(lines):
        stripped = lines[i].strip()
        if stripped.startswith('#!') or 'coding=' in stripped or 'coding:' in stripped:
            i += 1
        elif not stripped:
            i += 1
        else:
            break
    block = []
    if i < len(lines) and style == 'hash' and lines[i].lstrip().startswith('#'):
        while i < len(lines) and lines[i].lstrip().startswith('#'):
            block.append(lines[i].lstrip()[1:])
            i += 1
    elif i < len(lines) and lines[i].lstrip().startswith('//'):
        while i < len(lines) and lines[i].lstrip().startswith('//'):
            block.append(lines[i].lstrip()[2:])
            i += 1
    elif i < len(lines) and lines[i].lstrip().startswith('/*'):
        while i < len(lines):
            block.append(lines[i])
            if '*/' in lines[i]:
                break
            i += 1
    return '\n'.join(block)


def style_for(path: Path) -> str:
    """Hash comments for scripting sources, slashes for compiled ones."""
    if path.suffix in ('.py', '.sh', '.cmake', '.yaml', '.yml'):
        return 'hash'
    if path.name == 'CMakeLists.txt':
        return 'hash'
    return 'slash'


def problems_for(path: Path) -> list[str]:
    """The header complaint for one file, or nothing when it passes."""
    try:
        text = path.read_text(encoding='utf-8')
    except (OSError, UnicodeDecodeError) as exc:
        return [f'{path}: cannot be read: {exc}']
    block = first_block(text, style_for(path))
    if GENERATED_MARKER in block:
        return []
    has_new = SPDX_MARKER in block and HOLDER in block
    if OLD_MIT_MARKER in block:
        if has_new:
            return [f'{path}: carries both the SPDX header and the old MIT block']
        return [f'{path}: carries the old MIT block, expected the SPDX header']
    if has_new:
        return []
    return [f'{path}: missing the SPDX licence header']


def candidate_files(root: Path) -> list[Path]:
    """The checkout's tracked files plus untracked files git does not ignore.

    Outside a checkout there is no index, and the files present are the whole
    content, so all of them count and the rule stays meaningful in a tarball
    and in a test's throwaway tree.
    """
    try:
        listing = subprocess.run(
            [
                'git',
                '-C',
                str(root),
                'ls-files',
                '-z',
                '--cached',
                '--others',
                '--exclude-standard',
            ],
            capture_output=True,
            text=True,
            check=True,
        ).stdout
    except (OSError, subprocess.CalledProcessError):
        return sorted(p for p in root.rglob('*') if p.is_file())
    return [root / p for p in listing.split('\0') if p]


def check(root: Path) -> list[str]:
    """Every scoped source file under root, with one line per headerless file."""
    problems = []
    for path in candidate_files(root):
        if path.is_file() and in_scope(path, root):
            problems.extend(problems_for(path))
    return problems


def main() -> int:
    root = Path(__file__).resolve().parent.parent
    problems = check(root)
    for problem in problems:
        print(problem)
    return 1 if problems else 0


if __name__ == '__main__':
    sys.exit(main())
