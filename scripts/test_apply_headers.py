"""The header-applying tool: the bulk change runs through it, not by hand.

apply_headers.py walks the same scope the gate checks, replaces the old full
MIT block with the SPDX two-liner, inserts the header where one is missing,
and leaves generated and vendored files alone. The run is idempotent, and
named files outside the scope (the gate's own scripts) take the same path.
"""

from pathlib import Path

import apply_headers
import check_headers

SPDX = 'SPDX-License-Identifier: MIT'
HOLDER = 'Copyright (c) 2026 Alexis Pojomovsky and ros2serial contributors'
OLD_MARK = 'Permission is hereby granted'
OLD_HOLDER = 'Copyright (c) 2026 Alexis Pojomovsky'


def write(path: Path, text: str) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding='utf-8')
    return path


def old_block(prefix: str) -> str:
    return f'{prefix} {OLD_HOLDER}\n{prefix}\n{prefix} {OLD_MARK}, free of charge\n'


def test_replaces_a_slash_block_and_keeps_the_code(tmp_path):
    file = write(tmp_path / 'core' / 'src' / 'framer.c', old_block('//') + '\nint x;\n')
    assert apply_headers.apply_to_file(file) is True
    assert file.read_text(encoding='utf-8') == f'// {SPDX}\n// {HOLDER}\n\nint x;\n'


def test_replaces_a_hash_block_after_a_shebang(tmp_path):
    file = write(
        tmp_path / 'tools' / 'check.py',
        '#!/usr/bin/env python3\n' + old_block('#') + '\nx = 1\n',
    )
    assert apply_headers.apply_to_file(file) is True
    text = file.read_text(encoding='utf-8')
    assert text == f'#!/usr/bin/env python3\n# {SPDX}\n# {HOLDER}\n\nx = 1\n'


def test_inserts_a_missing_header(tmp_path):
    file = write(tmp_path / 'core' / 'src' / 'new.c', 'int x;\n')
    assert apply_headers.apply_to_file(file) is True
    assert file.read_text(encoding='utf-8') == f'// {SPDX}\n// {HOLDER}\n\nint x;\n'


def test_a_second_run_changes_nothing(tmp_path):
    file = write(tmp_path / 'core' / 'src' / 'framer.c', old_block('//') + '\nint x;\n')
    assert apply_headers.apply_to_file(file) is True
    assert apply_headers.apply_to_file(file) is False


def test_generated_files_stay_untouched(tmp_path):
    file = write(
        tmp_path / 'gen' / 'tests' / 'golden' / 'types' / 'float32.h',
        '/* Generated by r2s-gen 0.3.0 from the resolved types; do not edit. */\n',
    )
    assert apply_headers.apply_to_file(file) is False
    assert 'Generated by r2s-gen' in file.read_text(encoding='utf-8')


def test_walk_matches_the_gate_scope(tmp_path):
    scoped = write(tmp_path / 'core' / 'src' / 'old.c', old_block('//'))
    write(tmp_path / 'core' / 'tests' / 'vendor' / 'unity' / 'unity.c', old_block('//'))
    write(tmp_path / 'docs' / 'note.md', old_block('#'))
    targets = apply_headers.iter_targets(tmp_path)
    assert scoped in targets
    assert len(targets) == 1
    assert check_headers.check(tmp_path) != []


def test_walk_covers_scripts_and_yaml(tmp_path):
    script = write(tmp_path / 'scripts' / 'helper.py', 'x = 1\n')
    config = write(tmp_path / 'spec' / 'vectors' / 'frames' / 'ping.yaml', 'kind: frame\n')
    targets = apply_headers.iter_targets(tmp_path)
    assert script in targets
    assert config in targets


def test_named_files_cover_paths_outside_the_scope(tmp_path):
    file = write(tmp_path / 'scripts' / 'gate.py', old_block('#') + '\nx = 1\n')
    assert apply_headers.main([str(file)]) == 0
    assert file.read_text(encoding='utf-8') == f'# {SPDX}\n# {HOLDER}\n\nx = 1\n'


def test_named_yaml_takes_hash_comments(tmp_path):
    file = write(tmp_path / 'ports' / 'posix' / 'r2s.yaml', old_block('#') + '\nkey: 1\n')
    assert apply_headers.main([str(file)]) == 0
    assert file.read_text(encoding='utf-8') == f'# {SPDX}\n# {HOLDER}\n\nkey: 1\n'


def test_crlf_files_keep_their_endings(tmp_path):
    file = write(tmp_path / 'scripts' / 'job.sh', '#!/usr/bin/env bash\r\necho hi\r\n')
    assert apply_headers.apply_to_file(file) is True
    assert file.read_bytes() == (
        b'#!/usr/bin/env bash\r\n'
        b'# SPDX-License-Identifier: MIT\r\n'
        b'# Copyright (c) 2026 Alexis Pojomovsky and ros2serial contributors\r\n'
        b'\r\n'
        b'echo hi\r\n'
    )


def test_check_mode_reports_without_writing(tmp_path):
    file = write(tmp_path / 'core' / 'src' / 'old.c', old_block('//'))
    assert apply_headers.main(['--check', str(tmp_path)]) == 1
    assert OLD_MARK in file.read_text(encoding='utf-8')
