def test_every_exemption_names_its_reason():
    assert check_headers.EXEMPT_PREFIXES
    assert check_headers.EXEMPT_NAMES
    assert all(path and reason.strip() for path, reason in check_headers.EXEMPT_PREFIXES)
    assert all(name and reason.strip() for name, reason in check_headers.EXEMPT_NAMES)


def test_tree_carries_headers_on_every_source_file():
    assert check_headers.check(ROOT) == []


def init_repo(root: Path) -> None:
    subprocess.run(['git', 'init', '-q', str(root)], check=True)
    subprocess.run(['git', '-C', str(root), 'config', 'user.email', 't@example.com'], check=True)
    subprocess.run(['git', '-C', str(root), 'config', 'user.name', 't'], check=True)


def test_untracked_unignored_file_is_flagged(tmp_path):
    init_repo(tmp_path)
    file = write(tmp_path / 'core' / 'src' / 'new.c', 'int x;\n')
    assert check_headers.check(tmp_path) == [f'{file}: missing the SPDX licence header']


def test_ignored_residue_is_skipped(tmp_path):
    init_repo(tmp_path)
    write(tmp_path / '.gitignore', 'gen/cpp_stage/\n')
    write(tmp_path / 'gen' / 'cpp_stage' / 'src' / 'runtime.cpp', 'int x;\n')
    assert check_headers.check(tmp_path) == []
