"""The licence-header gate: every source file carries the MIT header.

The gate scans the hand-written sources under core, bridge, gen, ports,
examples and tools for the header ament_copyright accepts for MIT, and
generated files keep their own Generated by notice instead.
"""

from pathlib import Path

import check_headers

ROOT = Path(__file__).resolve().parent.parent

HOLDER = "Copyright (c) 2026 Alexis Pojomovsky"
MIT_MARK = "Permission is hereby granted"


def write(path: Path, text: str) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return path


def test_slash_header_passes(tmp_path):
    file = write(tmp_path / "core" / "src" / "framer.c", f"// {HOLDER}\n//\n// {MIT_MARK}, free of charge\n")
    assert check_headers.check(tmp_path) == []


def test_hash_header_passes_after_a_shebang(tmp_path):
    file = write(
        tmp_path / "tools" / "check.py",
        f"#!/usr/bin/env python3\n# {HOLDER}\n#\n# {MIT_MARK}, free of charge\n",
    )
    assert check_headers.check(tmp_path) == []


def test_headerless_source_fails(tmp_path):
    file = write(tmp_path / "bridge" / "r2s_bridge" / "src" / "router.cpp", "int x;\n")
    assert check_headers.check(tmp_path) == [f"{file}: missing the MIT licence header"]


def test_foreign_copyright_fails(tmp_path):
    file = write(
        tmp_path / "gen" / "r2s_gen" / "cli.py",
        "# Copyright 2020 Someone Else\n#\n# Permission is hereby granted, free of charge\n",
    )
    assert check_headers.check(tmp_path) == [f"{file}: missing the MIT licence header"]


def test_generated_notice_is_accepted(tmp_path):
    write(
        tmp_path / "gen" / "tests" / "golden" / "types" / "float32.h",
        "/* Generated by r2s-gen 0.3.0 from the resolved types; do not edit. */\n",
    )
    write(
        tmp_path / "ports" / "posix" / "src" / "r2s_generated.c",
        "/* Generated by r2s-gen 0.3.0 from r2s.yaml; do not edit. */\n",
    )
    assert check_headers.check(tmp_path) == []


def test_vendored_sources_are_skipped(tmp_path):
    write(tmp_path / "core" / "tests" / "vendor" / "unity" / "unity.c", "/* ThrowTheSwitch, MIT. */\n")
    assert check_headers.check(tmp_path) == []


def test_unscoped_dirs_are_skipped(tmp_path):
    write(tmp_path / "scripts" / "helper.py", "x = 1\n")
    assert check_headers.check(tmp_path) == []


def test_tree_carries_headers_on_every_source_file():
    assert check_headers.check(ROOT) == []
